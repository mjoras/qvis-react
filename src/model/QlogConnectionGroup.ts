// One loaded qlog FILE (qvis data/ConnectionGroup.ts). The name is historical: unrelated to `group_id`.

import type { Diagnostic } from "@/qlog/parse/diagnostics";
import type { Serialization } from "@/qlog/parse/normalize";
import { groupShorthand } from "./labels";
import { modelEvents } from "./modelEvents";
import type { QlogConnection } from "./QlogConnection";

const silentGroups = new WeakSet<QlogConnectionGroup>();

/**
 * @internal Runs `fn` without emitting model change events for `group` (the loader builds a fresh group that no
 * view references yet, so per-connection notifications would only cause useless store updates).
 */
export function withoutChangeEvents<T>(group: QlogConnectionGroup, fn: () => T): T {
    const already = silentGroups.has(group);
    silentGroups.add(group);
    try {
        return fn();
    } finally {
        if (!already) silentGroups.delete(group);
    }
}

export class QlogConnectionGroup {
    /** "urn:ietf:params:qlog:file:contained" | "...:sequential" | other (as logged, or inferred) */
    fileSchema = "";
    /** lower-cased media type ("application/qlog+json" / "application/qlog+json-seq") */
    serializationFormat = "";
    /** Display string for the Stats "qlog version" row (= fileSchema). */
    version = "";
    /** = serializationFormat (qvis field name kept; qvis default "JSON") */
    format = "JSON";
    /** Serialization the bytes actually had. */
    serialization: Serialization = "json";

    filename = "";
    title = "";
    description = "";
    URL = "";
    URLshort = "";
    /** PARITY: never populated (summary was removed in main-schema-06). */
    summary: Record<string, unknown> = {};

    /** Parse- and load-level diagnostics, deduplicated by code (DM1/DM2/DM3 toasts, Stats). */
    readonly diagnostics: Diagnostic[] = [];
    /** Union of the traces' event_schemas, first-seen order. */
    eventSchemas: readonly string[] = [];
    /** The normalized root object the group was loaded from (export: other top-level members). */
    rawRoot: Readonly<Record<string, unknown>> | undefined = undefined;

    private readonly connections: QlogConnection[] = [];

    /** Registers a connection (called by the QlogConnection constructor) and emits a model change. */
    addConnection(connection: QlogConnection): void {
        this.connections.push(connection);
        if (!silentGroups.has(this)) modelEvents.emit({ kind: "connection-added", group: this, connection });
    }

    /** All connections: traces, group_id slices, ERROR placeholders and generated clones (load order). */
    getConnections(): readonly QlogConnection[] {
        return this.connections;
    }

    /** Connections that are not sequence-diagram generated clones (Stats, export, shorthand). */
    getRealConnections(): readonly QlogConnection[] {
        return this.connections.filter((c) => !c.wasAutoGenerated);
    }

    /** File list second line, e.g. `My title : some description (2 connections)`. Counts real connections (D5). */
    getShorthand(): string {
        return groupShorthand(this, this.getRealConnections().length);
    }
}
