import { DATED_EPOCH, ev, file, loaded, refTime, trace } from "./__fixtures__/qlog";
import { modelEvents, type ModelChange } from "./modelEvents";
import { QlogConnection } from "./QlogConnection";
import { QlogConnectionGroup } from "./QlogConnectionGroup";
import { QlogLoader } from "./QlogLoader";
import { TimeTrackingMethod } from "./time";

beforeEach(() => {
    vi.spyOn(console, "warn").mockImplementation(() => {});
    vi.spyOn(console, "info").mockImplementation(() => {});
});
afterEach(() => vi.restoreAllMocks());

function conn(vantagePoint: QlogConnection["vantagePoint"] | undefined, title = "", description = ""): QlogConnection {
    const g = new QlogConnectionGroup();
    return new QlogConnection(g, { vantagePoint, title, description });
}

describe("QlogConnection.getLongName (fixture 12, data-model 3.3.4)", () => {
    it.each([
        [{ type: "client" }, "conn", "", "client : conn"],
        [{ name: "aioquic client", type: "client" }, "", "d", "aioquic client : client :  : d"],
        [
            { type: "unknown", flow: "unknown", name: "No VantagePoint set" },
            "",
            "",
            "No VantagePoint set : unknown (flow = unknown) : ",
        ],
        [{ type: "network", flow: "client" }, "t", "", "network (flow = client) : t"],
        [{ type: "unknown", flow: "unknown" }, "ERROR", "uri : desc", "unknown (flow = unknown) : ERROR : uri : desc"],
        [{ type: "server" }, "t", "d", "server : t : d"],
        [{ type: "" }, "x", "", "UNKNOWN : x"],
    ])("%o / %s / %s", (vp, title, description, expected) => {
        expect(conn(vp, title, description).getLongName()).toBe(expected);
    });

    it("constructor default vantage point", () => {
        const c = conn(undefined, "T");
        expect(c.vantagePoint).toEqual({ type: "unknown", flow: "unknown" });
        expect(c.getLongName()).toBe("unknown (flow = unknown) : T");
        expect(c.getVantagePointPerspective()).toBe("unknown");
    });
});

describe("QlogConnectionGroup.getShorthand (fixture 12, data-model 3.2.2)", () => {
    function group(title: string, description: string, n: number): QlogConnectionGroup {
        const g = new QlogConnectionGroup();
        g.title = title;
        g.description = description;
        for (let i = 0; i < n; i++) new QlogConnection(g);
        return g;
    }
    it("formats title, description (cut at 50) and connection count", () => {
        expect(group("My title", "some description", 2).getShorthand()).toBe(
            "My title : some description (2 connections)",
        );
        expect(group("", "", 1).getShorthand()).toBe(" (1 connection)");
        expect(group("", "", 0).getShorthand()).toBe(" (0 connections)");
        expect(group("T", "", 1).getShorthand()).toBe("T (1 connection)");
        const d50 = "x".repeat(50);
        expect(group("", d50, 1).getShorthand()).toBe(" : " + d50 + " (1 connection)");
        expect(group("", d50 + "y", 1).getShorthand()).toBe(" : " + d50 + "... (1 connection)");
    });

    it("counts real connections only (D5 / FIX Q11); ERROR placeholders count", () => {
        const g = QlogLoader.fromJSON(loaded(file([trace([ev(1, "quic:packet_sent")]), { error_description: "x" }])))!;
        expect(g.getShorthand()).toBe(" (2 connections)");
        const clone = g.getConnections()[0].clone();
        clone.wasAutoGenerated = true;
        expect(g.getConnections()).toHaveLength(3);
        expect(g.getRealConnections()).toHaveLength(2);
        expect(g.getShorthand()).toBe(" (2 connections)");
    });

    it("addConnection emits connection-added", () => {
        const g = new QlogConnectionGroup();
        const seen: ModelChange[] = [];
        const off = modelEvents.on((c) => seen.push(c));
        const c = new QlogConnection(g);
        off();
        expect(seen).toEqual([{ kind: "connection-added", group: g, connection: c }]);
        expect(g.getConnections()).toEqual([c]);
    });
});

describe("QlogConnection mutators emit change events", () => {
    it("setTitle / setDescription / setVantagePoint", () => {
        const c = conn({ type: "client" });
        const seen: ModelChange[] = [];
        const off = modelEvents.on((x) => seen.push(x));
        c.setTitle("t");
        c.setDescription("d");
        c.setVantagePoint({ type: "server", name: "n" });
        off();
        expect(seen.map((x) => (x.kind === "connection-changed" ? x.field : x.kind))).toEqual([
            "title",
            "description",
            "vantagePoint",
        ]);
        expect(c.getLongName()).toBe("n : server : t : d");
        expect(c.perspective).toBe("server");
    });

    it("ensureExt creates the slot object lazily", () => {
        const c = conn({ type: "client" });
        expect(c.ext).toBeUndefined();
        c.ensureExt().sequence = { manualTimeOffset: 5 };
        expect(c.ext?.sequence?.manualTimeOffset).toBe(5);
    });

    it("a listener that throws does not break emitters", () => {
        vi.spyOn(console, "error").mockImplementation(() => {});
        const ok = vi.fn();
        const off1 = modelEvents.on(() => {
            throw new Error("boom");
        });
        const off2 = modelEvents.on(ok);
        conn({ type: "client" }).setTitle("x"); // connection-added + connection-changed
        off1();
        off2();
        expect(ok).toHaveBeenCalledTimes(2);
    });
});

describe("QlogConnection.clone (fixture 13, data-model 3.16.10)", () => {
    function source() {
        const root = file([
            trace(
                [
                    ev(1, "quic:packet_sent", { n: 0 }),
                    ev(2, "quic:packet_received", { n: 1 }),
                    ev(3, "quic:recovery_metrics_updated", { n: 2 }),
                    ev(4, "quic:packet_sent", { n: 3 }),
                ],
                {
                    title: "T",
                    vantage_point: { type: "client" },
                    common_fields: { reference_time: refTime("unknown", "monotonic") },
                },
            ),
        ]);
        const g = QlogLoader.fromJSON(loaded(root))!;
        return { g, c: g.getConnections()[0] };
    }
    const seqTransform = (ev: { namespace: string; type: string }) =>
        ev.type === "packet_sent"
            ? { namespace: ev.namespace, type: "packet_received" }
            : ev.type === "packet_received"
              ? { namespace: ev.namespace, type: "packet_sent" }
              : { namespace: ev.namespace, type: "ignoreseq" };

    it("registers in the parent, builds its own index with swapped types, shares raw objects", () => {
        const { g, c } = source();
        c.getEvents()[0].ensureExt().sequence = { y: 10, timeText: "1.00" };
        c.ensureExt().sequence = { manualTimeOffset: 3 };

        const seen: ModelChange[] = [];
        const off = modelEvents.on((x) => {
            seen.push(x);
            // listeners run after the events are in place
            if (x.kind === "connection-added") expect(x.connection.getEvents()).toHaveLength(4);
        });
        const clone = c.clone(seqTransform);
        off();

        expect(seen).toEqual([{ kind: "connection-added", group: g, connection: clone }]);
        expect(g.getConnections()).toEqual([c, clone]);
        expect(clone.parent).toBe(g);
        expect(clone.wasAutoGenerated).toBe(false);
        expect(clone.rawTrace).toBeUndefined();
        expect(clone.title).toBe("T");

        expect(clone.getEvents().map((e) => e.fullName)).toEqual([
            "quic:packet_received",
            "quic:packet_sent",
            "quic:ignoreseq",
            "quic:packet_received",
        ]);
        expect(clone.lookup("quic", "packet_received").map((e) => e.data.n)).toEqual([0, 3]);
        expect(clone.lookup("quic", "packet_sent").map((e) => e.data.n)).toEqual([1]);
        expect(clone.lookup("quic", "ignoreseq")).toHaveLength(1);
        expect(c.lookup("quic", "packet_sent").map((e) => e.data.n)).toEqual([0, 3]); // original untouched
        expect(clone.getEvents()[0].raw).toBe(c.getEvents()[0].raw);
        expect(clone.getEvents()[0].loggedName).toBe("quic:packet_sent");
        expect(clone.getEvents()[0].conn).toBe(clone);
        expect(clone.getEvents().map((e) => e.relativeTime)).toEqual(c.getEvents().map((e) => e.relativeTime));

        // ext copied but independent
        expect(clone.getEvents()[0].ext?.sequence).toEqual({ y: 10, timeText: "1.00" });
        clone.getEvents()[0].ext!.sequence!.y = 99;
        expect(c.getEvents()[0].ext!.sequence!.y).toBe(10);
        expect(clone.ext?.sequence?.manualTimeOffset).toBe(3);
        clone.ext!.sequence!.manualTimeOffset = 7;
        expect(c.ext!.sequence!.manualTimeOffset).toBe(3);

        // own vantage point and timing (FIX Q8 / Q23)
        clone.vantagePoint.name = "GENERATED";
        expect(c.vantagePoint.name).toBeUndefined();
        expect(clone.timing).not.toBe(c.timing);
        expect(clone.timing.getTimeTrackingMethod()).toBe(TimeTrackingMethod.RELATIVE_TIME);
        clone.timing.setReferenceTime(100);
        expect(clone.getEvents()[0].absoluteTime).toBe(100);
        expect(c.getEvents()[0].absoluteTime).toBe(0);
    });

    it("sequence diagram usage: GENERATED label", () => {
        const { c } = source();
        const clone = c.clone(seqTransform);
        clone.setTitle("Simulated, autogenerated trace : " + c.title);
        clone.setDescription("Simulated, autogenerated trace : " + c.description);
        clone.setVantagePoint({ type: "server", flow: "unknown", name: "GENERATED" });
        clone.wasAutoGenerated = true;
        expect(clone.getLongName()).toBe(
            "GENERATED : server (flow = unknown) : Simulated, autogenerated trace : T : Simulated, autogenerated trace : ",
        );
    });

    it("identity clone without transform", () => {
        const { c } = source();
        const clone = c.clone();
        expect(clone.getEvents().map((e) => e.fullName)).toEqual(c.getEvents().map((e) => e.fullName));
        expect(clone.getLookupTable()).not.toBe(c.getLookupTable());
    });

    it("clone of a case R connection keeps absolute times", () => {
        const g = QlogLoader.fromJSON(
            loaded(
                file([trace([ev(5, "quic:packet_sent")], { common_fields: { reference_time: refTime(DATED_EPOCH) } })]),
            ),
        )!;
        const c = g.getConnections()[0];
        expect(c.clone().getEvents()[0].absoluteTime).toBe(c.getEvents()[0].absoluteTime);
    });
});
