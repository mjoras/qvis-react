// One trace, or one `group_id` slice of a trace (qvis data/Connection.ts). See data-model spec section 3.16.

import { connectionLabel } from "./labels";
import { modelEvents } from "./modelEvents";
import { QlogEvent } from "./QlogEvent";
import type { QlogConnectionGroup } from "./QlogConnectionGroup";
import { ConnectionTiming } from "./time";
import {
    DEFAULT_VANTAGE_POINT,
    type ConnectionExtensions,
    type EventExtensions,
    type EventNameParts,
    type ProtocolHint,
    type TraceErrorInfo,
    type VantagePoint,
} from "./types";

export interface QlogConnectionInit {
    title?: string;
    description?: string;
    vantagePoint?: VantagePoint;
    commonFields?: Record<string, unknown>;
    eventSchemas?: readonly string[];
    groupId?: string;
    traceIndex?: number;
    rawTrace?: Readonly<Record<string, unknown>>;
    isError?: boolean;
    traceError?: TraceErrorInfo;
    wasAutoGenerated?: boolean;
    /** Register in `parent` (qvis constructor side effect). Default true. */
    register?: boolean;
}

type LookupTable = Map<string, Map<string, QlogEvent[]>>;

const EMPTY_EVENTS: readonly QlogEvent[] = Object.freeze([]) as readonly QlogEvent[];
const QUIC_H3_SCHEMA_RE = /^urn:ietf:params:qlog:events:(quic|http3)(-\d+)?(#.*)?$/;

function copyExt<T extends object>(ext: T | undefined): T | undefined {
    if (ext === undefined) return undefined;
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(ext)) {
        out[k] = typeof v === "object" && v !== null && !Array.isArray(v) ? { ...(v as object) } : v;
    }
    return out as T;
}

export class QlogConnection {
    readonly parent: QlogConnectionGroup;
    /** mutate through setTitle (change notification) */
    title: string;
    /** mutate through setDescription (change notification) */
    description: string;
    /** own copy (never shared with the raw JSON or other slices); mutate through setVantagePoint */
    vantagePoint: VantagePoint;
    /** the trace's common_fields ({} default); shared with the raw JSON, never mutated */
    readonly commonFields: Record<string, unknown>;
    readonly eventSchemas: readonly string[];
    /** set for group_id slices (the slice's id), undefined when the trace was not split */
    readonly groupId: string | undefined;
    /** index in file.traces (-1 when not loaded from a file) */
    readonly traceIndex: number;
    /** the trace (or TraceError) object it was loaded from; undefined for clones */
    readonly rawTrace: Readonly<Record<string, unknown>> | undefined;
    /** TraceError placeholder ("ERROR" title, no events) */
    readonly isError: boolean;
    readonly traceError: TraceErrorInfo | undefined;
    /** true for sequence-diagram generated clones (set by the caller of clone()) */
    wasAutoGenerated: boolean;
    readonly timing: ConnectionTiming;
    /** renderer annotations (lazily created; never serialized) */
    ext: Partial<ConnectionExtensions> | undefined = undefined;

    private events: QlogEvent[] = [];
    private lookupTable: LookupTable = new Map();

    constructor(parent: QlogConnectionGroup, init: QlogConnectionInit = {}) {
        this.parent = parent;
        this.title = init.title ?? "";
        this.description = init.description ?? "";
        this.vantagePoint = init.vantagePoint ?? { ...DEFAULT_VANTAGE_POINT };
        this.commonFields = init.commonFields ?? {};
        this.eventSchemas = init.eventSchemas ?? [];
        this.groupId = init.groupId;
        this.traceIndex = init.traceIndex ?? -1;
        this.rawTrace = init.rawTrace;
        this.isError = init.isError ?? false;
        this.traceError = init.traceError;
        this.wasAutoGenerated = init.wasAutoGenerated ?? false;
        this.timing = new ConnectionTiming(this);
        if (init.register !== false) parent.addConnection(this);
    }

    /**
     * @internal Sets the (already sorted) events and builds the lookup index. Used by the loader and clone().
     * Events must reference this connection.
     */
    initEvents(events: QlogEvent[]): void {
        this.events = events;
        const table: LookupTable = new Map();
        let lastNs: string | undefined;
        let lastType: string | undefined;
        let lastArr: QlogEvent[] | undefined;
        for (let i = 0; i < events.length; i++) {
            const ev = events[i];
            if (ev.type === lastType && ev.namespace === lastNs) {
                lastArr!.push(ev);
                continue;
            }
            let byType = table.get(ev.namespace);
            if (byType === undefined) {
                byType = new Map();
                table.set(ev.namespace, byType);
            }
            let arr = byType.get(ev.type);
            if (arr === undefined) {
                arr = [];
                byType.set(ev.type, arr);
            }
            arr.push(ev);
            lastNs = ev.namespace;
            lastType = ev.type;
            lastArr = arr;
        }
        this.lookupTable = table;
    }

    /** The events in time order (stable). The array is the internal one: do not mutate it. */
    getEvents(): readonly QlogEvent[] {
        return this.events;
    }

    /** Events of one `namespace:type`, in event order. Always valid (eager index); a shared empty array if none. */
    lookup(namespace: string, type: string): readonly QlogEvent[] {
        const byType = this.lookupTable.get(namespace);
        if (byType === undefined) return EMPTY_EVENTS;
        return byType.get(type) ?? EMPTY_EVENTS;
    }

    /** Map<namespace, Map<type, events>>, first-seen order (Stats histogram). */
    getLookupTable(): ReadonlyMap<string, ReadonlyMap<string, readonly QlogEvent[]>> {
        return this.lookupTable;
    }

    /** No-op porting aid: the index is built eagerly at load. */
    setupLookupTable(): void {
        // intentionally empty
    }

    /** Porting shim for qvis `parseEvent(evt)`: identity. */
    parseEvent(ev: QlogEvent): QlogEvent {
        return ev;
    }

    /** Porting shim for qvis `getEventParser()`: the connection's timing (`load(ev)` returns `ev`). */
    getEventParser(): ConnectionTiming {
        return this.timing;
    }

    /** = timing.getAbsoluteStartTime() */
    get startTime(): number {
        return this.timing.getAbsoluteStartTime();
    }

    /** First and last relativeTime, or undefined for a connection without events. */
    timeRange(): { minRelative: number; maxRelative: number } | undefined {
        const n = this.events.length;
        if (n === 0) return undefined;
        return { minRelative: this.events[0].relativeTime, maxRelative: this.events[n - 1].relativeTime };
    }

    /**
     * "client" / "server" for those vantage point types; otherwise (network, unknown) the `flow` when it is client or
     * server; else "unknown" (Connection.ts:113-124).
     */
    getVantagePointPerspective(): "client" | "server" | "unknown" {
        const { type, flow } = this.vantagePoint;
        if (type === "server") return "server";
        if (type === "client") return "client";
        // network or unknown: look at the flow (also robust for "unknown", which should not have a flow)
        if (flow === "client") return "client";
        if (flow === "server") return "server";
        return "unknown";
    }

    /** = getVantagePointPerspective() */
    get perspective(): "client" | "server" | "unknown" {
        return this.getVantagePointPerspective();
    }

    /** `[name : ]type[ (flow = f)] : title[ : description]` (Connection.ts:163-186, verbatim). */
    getLongName(): string {
        return connectionLabel(this);
    }

    /**
     * data-model 3.16.6: `common_fields.protocol_type` when present (qvis-internal converter values "TCP_HTTP2",
     * "TCP", "QUIC_HTTP3"); else derived from the observed namespaces (`tcp` + `http2` -> "TCP_HTTP2", `tcp` ->
     * "TCP"); else "QUIC_HTTP3" when event_schemas or the events use the quic / http3 namespaces; else "unknown".
     */
    get protocolHint(): ProtocolHint {
        const pt = this.commonFields.protocol_type;
        if (typeof pt === "string" && pt !== "") return pt;
        // a trace that also logs quic:* events stays a QUIC trace (a stray tcp: event must not switch the transport)
        if (this.lookupTable.has("tcp") && !this.lookupTable.has("quic")) {
            return this.lookupTable.has("http2") ? "TCP_HTTP2" : "TCP";
        }
        for (const s of this.eventSchemas) if (QUIC_H3_SCHEMA_RE.test(s)) return "QUIC_HTTP3";
        if (this.lookupTable.has("quic") || this.lookupTable.has("http3")) return "QUIC_HTTP3";
        return "unknown";
    }

    /**
     * Namespace of this trace's packet_sent / packet_received events (data-model 9.10, D9): "tcp" for TCP traces
     * from the ported tshark converter (protocolHint "TCP" / "TCP_HTTP2"), else "quic".
     */
    get transportNamespace(): "quic" | "tcp" {
        const hint = this.protocolHint;
        return hint === "TCP" || hint === "TCP_HTTP2" ? "tcp" : "quic";
    }

    setTitle(title: string): void {
        this.title = title;
        modelEvents.emit({ kind: "connection-changed", connection: this, field: "title" });
    }

    setDescription(description: string): void {
        this.description = description;
        modelEvents.emit({ kind: "connection-changed", connection: this, field: "description" });
    }

    setVantagePoint(vantagePoint: VantagePoint): void {
        this.vantagePoint = vantagePoint;
        modelEvents.emit({ kind: "connection-changed", connection: this, field: "vantagePoint" });
    }

    /** Returns `ext`, creating it on first use. */
    ensureExt(): Partial<ConnectionExtensions> {
        let ext = this.ext;
        if (ext === undefined) {
            ext = {};
            this.ext = ext;
        }
        return ext;
    }

    /**
     * Simulated peer trace (sequence diagram). Returns a NEW connection registered in the same group (it appears in
     * every selector, qvis parity Q10) with copied title / description / vantagePoint / commonFields / timing, new
     * QlogEvent wrappers over the same raw objects (raw is never mutated, so no deep copy), copied `ext` slots, and
     * its own lookup index built from the transformed names. `wasAutoGenerated` is left false; the caller sets it.
     * The "connection-added" change is emitted after the events are in place.
     */
    clone(transform?: (ev: QlogEvent) => EventNameParts): QlogConnection {
        const out = new QlogConnection(this.parent, {
            title: this.title,
            description: this.description,
            vantagePoint: { ...this.vantagePoint },
            commonFields: { ...this.commonFields },
            eventSchemas: this.eventSchemas.slice(),
            groupId: this.groupId,
            traceIndex: this.traceIndex,
            rawTrace: undefined,
            isError: this.isError,
            traceError: this.traceError,
            wasAutoGenerated: false,
            register: false,
        });
        out.timing.copyFrom(this.timing);
        if (this.ext !== undefined) out.ext = copyExt(this.ext);
        const src = this.events;
        const events: QlogEvent[] = new Array(src.length);
        for (let i = 0; i < src.length; i++) {
            const ev = src[i];
            let namespace = ev.namespace;
            let type = ev.type;
            let fullName = ev.fullName;
            if (transform) {
                const t = transform(ev);
                namespace = t.namespace;
                type = t.type;
                fullName = namespace + ":" + type;
            }
            const copy = new QlogEvent(
                out,
                ev.raw,
                ev.originalIndex,
                ev.index,
                ev.loggedName,
                fullName,
                namespace,
                type,
                ev.data,
                ev.time,
                ev.resolvedTime,
                ev.groupId,
                ev.tuple,
                ev.malformed,
            );
            if (ev.ext !== undefined) copy.ext = copyExt<Partial<EventExtensions>>(ev.ext);
            events[i] = copy;
        }
        out.initEvents(events);
        this.parent.addConnection(out);
        return out;
    }
}
