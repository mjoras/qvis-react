import {
    combinedConnectionOptionLabel,
    combinedGroupHeaderLabel,
    combinedHeaderLabel,
    connectionLabel,
    connectionOptionLabel,
    fileListLabel,
    groupOptionLabel,
    groupShorthand,
    multiplexingTraceHeading,
    sequenceHeaderTitle,
    sequenceHeaderVantageText,
    statsLocalHeading,
    statsRemoteHeading,
    statsVantageLines,
    statsVantageText,
} from "./labels";

describe("labels (app-shell 2.5.5, data-model 2.1)", () => {
    it("connection labels (app-shell 2.5.5 table)", () => {
        expect(
            connectionLabel({
                vantagePoint: { name: "aioquic client", type: "client" },
                title: "Connection 1",
                description: "",
            }),
        ).toBe("aioquic client : client : Connection 1");
        expect(connectionLabel({ vantagePoint: { type: "server" }, title: "t", description: "d" })).toBe(
            "server : t : d",
        );
        expect(connectionLabel({ vantagePoint: { type: "network", flow: "client" }, title: "", description: "" })).toBe(
            "network (flow = client) : ",
        );
        const noVp = { type: "unknown", flow: "unknown", name: "No VantagePoint set" };
        expect(connectionLabel({ vantagePoint: noVp, title: "x", description: "" })).toBe(
            "No VantagePoint set : unknown (flow = unknown) : x",
        );
        expect(connectionLabel({ vantagePoint: { type: "client" }, title: "Group abc : T", description: "" })).toBe(
            "client : Group abc : T",
        );
        expect(connectionLabel({ title: "t", description: "" })).toBe("t");
        expect(connectionOptionLabel({ vantagePoint: { type: "server" }, title: "t", description: "" })).toBe(
            "server : t",
        );
        expect(combinedConnectionOptionLabel({ vantagePoint: { type: "server" }, title: "t", description: "" })).toBe(
            "↳ server : t",
        );
    });

    it("group labels", () => {
        expect(groupOptionLabel({ filename: "foo.qlog", title: "My title", description: "My description" })).toBe(
            "foo.qlog (My title : My description)",
        );
        expect(groupOptionLabel({ filename: "foo.qlog", title: "", description: "" })).toBe("foo.qlog ()");
        expect(combinedGroupHeaderLabel({ filename: "foo.qlog" })).toBe("foo.qlog");
        const c = {
            vantagePoint: { type: "client" },
            title: "t",
            description: "",
            parent: { filename: "f.qlog", description: "" },
        };
        expect(combinedHeaderLabel(c)).toBe("f.qlog ()");
        expect(multiplexingTraceHeading(c)).toBe("f.qlog : client : t");
        expect(groupShorthand({ title: "", description: "" }, 3)).toBe(" (3 connections)");
    });

    it("file list and sequence diagram headers", () => {
        expect(fileListLabel({ filename: "a.qlog", URL: "", URLshort: "" })).toEqual({ kind: "text", text: "a.qlog" });
        expect(fileListLabel({ filename: "x", URL: "https://h/a.qlog", URLshort: "h/a.qlog" })).toEqual({
            kind: "link",
            href: "https://h/a.qlog",
            text: "h/a.qlog",
        });
        const parent = { filename: "a.qlog", description: "", URL: "https://h/a.qlog", URLshort: "short" };
        const c = { vantagePoint: { type: "client" }, title: "", description: "", parent };
        expect(sequenceHeaderTitle(c)).toEqual({ kind: "link", href: "https://h/a.qlog", text: "short" });
        expect(sequenceHeaderTitle({ ...c, wasAutoGenerated: true })).toEqual({
            kind: "text",
            text: "GENERATED: a.qlog",
        });
        expect(sequenceHeaderTitle({ ...c, parent: { ...parent, URL: "" } })).toEqual({ kind: "text", text: "a.qlog" });
        // only http(s) / relative URLs become links (no javascript: / data: hrefs from ?file=)
        for (const bad of [
            "javascript:alert(1)",
            " JavaScript:alert(1)",
            "java\tscript:x",
            "data:text/html,<b>x</b>",
        ]) {
            expect(sequenceHeaderTitle({ ...c, parent: { ...parent, URL: bad } })).toEqual({
                kind: "text",
                text: "short",
            });
            expect(fileListLabel({ filename: "x", URL: bad, URLshort: "s" })).toEqual({ kind: "text", text: "s" });
        }
        expect(fileListLabel({ filename: "x", URL: "examples/a.qlog", URLshort: "s" }).kind).toBe("link");
        expect(fileListLabel({ filename: "x", URL: "HTTPS://h/a.qlog", URLshort: "s" }).kind).toBe("link");
        expect(sequenceHeaderVantageText(c)).toBe("client");
        expect(sequenceHeaderVantageText({ ...c, vantagePoint: { type: "network", flow: "server" } })).toBe(
            "network : from server's viewpoint",
        );
        expect(sequenceHeaderVantageText({ ...c, vantagePoint: { type: "network" } })).toBe(
            "network : from unknown's viewpoint",
        );
    });

    it("stats labels", () => {
        const c = { vantagePoint: { type: "client", name: "n" }, title: "", description: "" };
        expect(statsVantageLines(c)).toEqual(["n", "client"]);
        expect(statsVantageText({ ...c, vantagePoint: { type: "network", flow: "client", name: "" } })).toBe(
            "network : with client perspective",
        );
        expect(statsVantageText({ ...c, vantagePoint: { type: "network" } })).toBe("network : with  perspective");
        expect(statsLocalHeading(c)).toBe("Local (client)");
        expect(statsLocalHeading(c, "Local Streams")).toBe("Local Streams (client)");
        expect(statsRemoteHeading(c)).toBe("Remote (server)");
        expect(statsRemoteHeading({ ...c, vantagePoint: { type: "server" } }, "Remote Streams")).toBe(
            "Remote Streams (client)",
        );
    });
});
