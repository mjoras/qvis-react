// User-visible labels computed from model fields (data-model spec section 2.1, app-shell spec section 2.5.5).
// Verbatim qvis formulas. Pure functions over minimal structural types, so plain objects work in tests and the
// model classes satisfy them.

export interface LabelVantagePoint {
    name?: string;
    type?: string;
    flow?: string;
}

export interface LabelConnection {
    title: string;
    description: string;
    vantagePoint?: LabelVantagePoint;
}

export interface LabelGroup {
    filename: string;
    title: string;
    description: string;
}

export interface LabelConnectionWithParent extends LabelConnection {
    parent: { filename: string; description: string; URL?: string; URLshort?: string };
    wasAutoGenerated?: boolean;
}

/** Prefix of connection rows in the combined select: U+21B3 followed by one space. */
export const COMBINED_CONNECTION_PREFIX = "↳ ";

/**
 * `Connection.getLongName()` and the selector's connection label (ConnectionConfigurator.vue:136-157):
 * `[name + " : "] + (type || "UNKNOWN") + (flow ? " (flow = " + flow + ") : " : " : ") + title + [" : " + description]`.
 */
export function connectionLabel(c: LabelConnection): string {
    let s = "";
    const vp = c.vantagePoint;
    if (vp) {
        if (vp.name) s += vp.name + " : ";
        s += vp.type ? vp.type : "UNKNOWN";
        s += vp.flow ? " (flow = " + vp.flow + ") : " : " : ";
    }
    if (c.title) s += c.title;
    if (c.description) s += " : " + c.description;
    return s;
}

/** Connection option in separate-select mode (identical to {@link connectionLabel}). */
export function connectionOptionLabel(c: LabelConnection): string {
    return connectionLabel(c);
}

/** Connection option in combined mode: `"↳ " + connectionLabel(c)`. */
export function combinedConnectionOptionLabel(c: LabelConnection): string {
    return COMBINED_CONNECTION_PREFIX + connectionLabel(c);
}

/** Group option (separate-select / group-only modes): `filename + " (" + [title + " : "] + description + ")"`. */
export function groupOptionLabel(g: LabelGroup): string {
    return g.filename + " (" + (g.title ? g.title + " : " : "") + g.description + ")";
}

/** Group header option in combined mode: the filename. */
export function combinedGroupHeaderLabel(g: Pick<LabelGroup, "filename">): string {
    return g.filename;
}

/** Combined mode header row above the select: `parent.filename + " (" + parent.description + ")"`. */
export function combinedHeaderLabel(c: Pick<LabelConnectionWithParent, "parent">): string {
    return c.parent.filename + " (" + c.parent.description + ")";
}

/** Multiplexing graph per-trace `<h4>`: `parent.filename + " : " + getLongName()`. */
export function multiplexingTraceHeading(c: LabelConnectionWithParent): string {
    return c.parent.filename + " : " + connectionLabel(c);
}

/**
 * True when `url` may be used as a link href: http(s) or relative (resolves against the http(s) page). Any other
 * scheme (`javascript:`, `data:`, ...) is refused (file-loading Q3 FIX). `?file=data:...` can produce a loaded group
 * whose URL is a data: URL, because `fetch` accepts it. Mirrors the WHATWG parser's stripping of leading C0 controls
 * / spaces and of tabs and newlines anywhere.
 */
export function isSafeLinkURL(url: string): boolean {
    let start = 0;
    while (start < url.length && url.charCodeAt(start) <= 0x20) start++; // leading C0 controls and spaces
    const s = url.slice(start).replace(/[\t\n\r]/g, "");
    const scheme = /^([a-zA-Z][a-zA-Z0-9+.-]*):/.exec(s);
    if (scheme === null) return true;
    const lower = scheme[1].toLowerCase();
    return lower === "http" || lower === "https";
}

/**
 * File list first line: a link to `URL` with text `URLshort` when URL is non-empty (only http(s) / relative URLs
 * become links; others are shown as plain `URLshort` text), else the filename.
 */
export function fileListLabel(g: {
    filename: string;
    URL?: string;
    URLshort?: string;
}): { kind: "link"; href: string; text: string } | { kind: "text"; text: string } {
    if (g.URL) {
        return isSafeLinkURL(g.URL)
            ? { kind: "link", href: g.URL, text: g.URLshort ?? "" }
            : { kind: "text", text: g.URLshort ?? "" };
    }
    return { kind: "text", text: g.filename };
}

/**
 * Sequence diagram column header line 1: an SVG link to `parent.URL` (text `parent.URLshort`) when the connection
 * is not generated and the parent has a URL, else `(wasAutoGenerated ? "GENERATED: " : "") + parent.filename`.
 */
export function sequenceHeaderTitle(
    c: LabelConnectionWithParent,
): { kind: "link"; href: string; text: string } | { kind: "text"; text: string } {
    if (!c.wasAutoGenerated && c.parent.URL) {
        return isSafeLinkURL(c.parent.URL)
            ? { kind: "link", href: c.parent.URL, text: c.parent.URLshort ?? "" }
            : { kind: "text", text: c.parent.URLshort ?? "" };
    }
    return { kind: "text", text: (c.wasAutoGenerated ? "GENERATED: " : "") + c.parent.filename };
}

/** Sequence diagram column header line 2: `type`, or `"network : from " + flow + "'s viewpoint"` for network. */
export function sequenceHeaderVantageText(c: LabelConnection): string {
    const vp = c.vantagePoint;
    // sequence-diagram LD6: a network trace without flow reads "from unknown's viewpoint" (qvis printed "undefined")
    if (vp && vp.type === "network") return "network : from " + (vp.flow ?? "unknown") + "'s viewpoint";
    return vp ? "" + vp.type : "undefined";
}

/** Alias (data-model spec 8.1 name). */
export const seqHeaderVantageText = sequenceHeaderVantageText;

/**
 * Stats "Vantage point" cell lines: `name` (if non-empty), then `type` or `"network : with " + flow + " perspective"`.
 * qvis joined them with `<br/>`.
 */
export function statsVantageLines(c: LabelConnection): string[] {
    const vp = c.vantagePoint;
    const lines: string[] = [];
    if (!vp) return lines;
    if (vp.name !== undefined && vp.name !== "") lines.push(vp.name);
    // statistics.md §6.2: network without flow reads "network : with  perspective" (`flow ?? ""`)
    lines.push(vp.type === "network" ? "network : with " + (vp.flow ?? "") + " perspective" : "" + vp.type);
    return lines;
}

/** Stats vantage text as one string, lines joined with "\n". */
export function statsVantageText(c: LabelConnection): string {
    return statsVantageLines(c).join("\n");
}

/** Stats flow-control headings: `prefix + " (" + type + ")"`, e.g. `Local (client)`, `Local Streams (client)`. */
export function statsLocalHeading(c: LabelConnection, prefix = "Local"): string {
    return prefix + " (" + (c.vantagePoint ? c.vantagePoint.type : undefined) + ")";
}

/** `prefix + " (" + (type === "client" ? "server" : "client") + ")"`, e.g. `Remote (server)`. */
export function statsRemoteHeading(c: LabelConnection, prefix = "Remote"): string {
    return prefix + " (" + (c.vantagePoint && c.vantagePoint.type === "client" ? "server" : "client") + ")";
}

/**
 * `QlogConnectionGroup.getShorthand()` formula (ConnectionGroup.ts:37-60): title, `" : " + description` (cut to 50
 * characters + "..."), then `" (N connections)"` / `" (1 connection)"`.
 */
export function groupShorthand(g: { title: string; description: string }, connectionCount: number): string {
    let output = "";
    if (g.title) output += g.title;
    if (g.description) {
        if (g.description.length <= 50) output += " : " + g.description;
        else output += " : " + g.description.substring(0, 50) + "...";
    }
    if (connectionCount !== 1) output += " (" + connectionCount + " connections)";
    else output += " (1 connection)";
    return output;
}
