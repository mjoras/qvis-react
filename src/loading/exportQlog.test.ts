function buildRoot(): Record<string, unknown> {
    return {
        file_schema: "urn:ietf:params:qlog:file:contained",
        serialization_format: "application/qlog+json",
        title: "file title",
        description: "file description",
        summary: { removed: "in -06" },
        code_version: "v1.2.3",
        traces: [
            {
                title: "plain",
                vantage_point: { name: "c", type: "client" },
                event_schemas: ["urn:ietf:params:qlog:events:quic-13"],
                configuration: { time_offset: 0 },
                custom_member: 42,
                common_fields: { reference_time: { clock_type: "monotonic", epoch: "unknown" } },
                events: [
                    {
                        time: 2,
                        name: "quic:packet_received",
                        data: { header: { packet_type: "1RTT", packet_number: 1 } },
                    },
                    { time: 1, name: "quic:packet_sent", data: { header: { packet_type: "1RTT", packet_number: 0 } } },
                ],
            },
            { error_description: "download failed", uri: "https://x/y.pcap" },
            {
                title: "T",
                vantage_point: { type: "server" },
                event_schemas: ["urn:ietf:params:qlog:events:quic"],
                events: [
                    { time: 1, name: "quic:packet_sent", group_id: "a", data: {} },
                    { time: 2, name: "quic:packet_sent", group_id: "b", data: {} },
                    { time: 3, name: "quic:packet_received", group_id: "a", data: {} },
                ],
            },
            {
                vantage_point: { type: "client" },
                events: [
                    { time: 0, name: "http3:frame_created", data: {} },
                    { time: 1, name: "quic:packet_sent", data: {} },
                ],
            },
        ],
    };
}

function load(): { group: QlogConnectionGroup; root: Record<string, unknown>; snapshot: string } {
    const root = buildRoot();
    const snapshot = JSON.stringify(root);
    const group = QlogLoader.fromJSON({ root, serialization: "json", diagnostics: [] }, { filename: "f.qlog" });
    if (group === undefined) throw new Error("model rejected the test file");
    return { group, root, snapshot };
}

