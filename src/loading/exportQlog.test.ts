describe("groupToContainedQlog (file-loading 3.11 NEW)", () => {
    it("emits a latest-draft contained file from the raw traces", () => {
        const { group, root, snapshot } = load();
        // a sequence-diagram mirror trace must be skipped
        const clone = group.getConnections()[0].clone();
        clone.wasAutoGenerated = true;

        const out = groupToContainedQlog(group);
        expect(out.file_schema).toBe("urn:ietf:params:qlog:file:contained");
        expect(out.serialization_format).toBe("application/qlog+json");
        expect(out.title).toBe("file title");
        expect(out.description).toBe("file description");
        expect(out.code_version).toBe("v1.2.3");
        expect(out).not.toHaveProperty("summary");

        const traces = out.traces as Array<Record<string, unknown>>;
        expect(traces).toHaveLength(5); // plain + TraceError + 2 group_id slices + untitled

        const rawTraces = root.traces as Array<Record<string, unknown>>;
        // unsplit trace: the raw event objects in the connection's sorted order (9.6 PARITY), configuration
        // dropped, other members kept
        const rawEvents0 = rawTraces[0].events as unknown[];
        expect(traces[0].events).toEqual([rawEvents0[1], rawEvents0[0]]);
        expect((traces[0].events as unknown[])[0]).toBe(rawEvents0[1]);
        expect(traces[0]).not.toHaveProperty("configuration");
        expect(traces[0].custom_member).toBe(42);
        expect(traces[0].event_schemas).toEqual(["urn:ietf:params:qlog:events:quic-13"]);
        expect(traces[0].common_fields).toEqual({ reference_time: { clock_type: "monotonic", epoch: "unknown" } });
        expect(traces[0].title).toBe("plain");

        // TraceError round trip (FIX)
        expect(traces[1]).toEqual({ error_description: "download failed", uri: "https://x/y.pcap" });

        // group_id slices stay split; loader-generated "Group X : " titles export the raw title (D15)
        expect(traces[2].title).toBe("T");
        expect(traces[3].title).toBe("T");
        expect((traces[2].events as unknown[]).length).toBe(2);
        expect((traces[3].events as unknown[]).length).toBe(1);
        expect((traces[2].events as unknown[])[0]).toBe((rawTraces[2].events as unknown[])[0]);

        // event_schemas derived from the namespaces when absent, with the draft suffixes (9.6)
        expect(traces[4].event_schemas).toEqual([
            "urn:ietf:params:qlog:events:quic-13",
            "urn:ietf:params:qlog:events:http3-13",
        ]);

        // raw input never mutated
        expect(JSON.stringify(root)).toBe(snapshot);
    });

    it("round-trips through the loader", async () => {
        const { group } = load();
        const text = serializeGroup(group);
        expect(text).toContain('\n  "file_schema"'); // 2-space pretty print
        const loaded = await loadQlogFile(text, "export.qlog");
        const again = QlogLoader.fromJSON(loaded, { filename: "export.qlog" });
        expect(again?.getConnections().length).toBe(group.getRealConnections().length);
    });

    it("deriveEventSchemas", () => {
        expect(deriveEventSchemas([{ name: "loglevel:info" }, { name: "nocolon" }, {}, null])).toEqual([
            "urn:ietf:params:qlog:events:loglevel",
        ]);
        expect(deriveEventSchemas([{ name: "http:capsule_parsed" }, { name: "tcp:packet_sent" }])).toEqual([
            "urn:ietf:params:qlog:events:http-13",
        ]);
    });

    it("re-loading an exported group_id split keeps the slice titles (no 'Group a : Group a : ', D15)", async () => {
        const { group } = load();
        group.getConnections()[3].setTitle("renamed"); // a renamed slice title is exported as is
        const loaded = await loadQlogFile(serializeGroup(group), "export.qlog");
        const again = QlogLoader.fromJSON(loaded, { filename: "export.qlog" })!;
        const titles = again.getConnections().map((c) => c.title);
        expect(titles).toContain("Group a : T");
        expect(titles).toContain("Group b : renamed");
        expect(titles.some((t) => t.includes("Group a : Group a"))).toBe(false);
    });

    it("time rule: relative_to_previous_event traces are exported with resolved times (9.6)", async () => {
        const root = {
            file_schema: "urn:ietf:params:qlog:file:contained",
            serialization_format: "application/qlog+json",
            traces: [
                {
                    vantage_point: { type: "client" },
                    event_schemas: ["urn:ietf:params:qlog:events:quic-13"],
                    common_fields: {
                        time_format: "relative_to_previous_event",
                        reference_time: { clock_type: "system", epoch: "2024-01-01T00:00:00Z" },
                    },
                    events: [
                        { time: 10, name: "quic:packet_sent", group_id: "a", data: {} },
                        { time: 5, name: "quic:packet_sent", group_id: "b", data: {} },
                        { time: 5, name: "quic:packet_received", group_id: "a", data: {} },
                        { name: "quic:packet_received", group_id: "b", data: {} },
                    ],
                },
            ],
        };
        const snapshot = JSON.stringify(root);
        const group = QlogLoader.fromJSON({ root, serialization: "json", diagnostics: [] }, { filename: "d.qlog" })!;
        const out = groupToContainedQlog(group);
        const traces = out.traces as Array<Record<string, unknown>>;
        expect(traces).toHaveLength(2);
        expect(traces[0].common_fields).toEqual({
            time_format: "relative_to_epoch",
            reference_time: { clock_type: "system", epoch: "2024-01-01T00:00:00Z" },
        });
        expect((traces[0].events as Array<{ time: number }>).map((e) => e.time)).toEqual([10, 20]);
        // the malformed (time-less) event gets its resolved time, so the output never lacks `time`
        expect((traces[1].events as Array<{ time: number }>).map((e) => e.time)).toEqual([15, 20]);
        expect(JSON.stringify(root)).toBe(snapshot);

        // re-loading the export gives the same absolute times per slice
        const again = QlogLoader.fromJSON(await loadQlogFile(serializeGroup(group), "d2.qlog"), { filename: "d2" })!;
        const times = (c: QlogConnectionGroup) =>
            c.getConnections().map((conn) => conn.getEvents().map((e) => e.absoluteTime));
        expect(times(again)).toEqual(times(group));
    });

    it("omits the loader-injected default vantage point when the raw trace had none (9.6)", () => {
        const root = {
            file_schema: "urn:ietf:params:qlog:file:contained",
            serialization_format: "application/qlog+json",
            traces: [
                { event_schemas: [], events: [{ time: 0, name: "quic:packet_sent", data: {} }] },
                { event_schemas: [], events: [{ time: 0, name: "quic:packet_sent", data: {} }] },
            ],
        };
        const group = QlogLoader.fromJSON({ root, serialization: "json", diagnostics: [] }, { filename: "v.qlog" })!;
        group.getConnections()[1].setVantagePoint({ type: "client", name: "guessed" }); // a rename is kept
        const traces = groupToContainedQlog(group).traces as Array<Record<string, unknown>>;
        expect(traces[0]).not.toHaveProperty("vantage_point");
        expect(traces[1].vantage_point).toEqual({ type: "client", name: "guessed" });
        expect(traces[0].event_schemas).toEqual(["urn:ietf:params:qlog:events:quic-13"]);
    });
});

describe("own '__proto__' members (security review)", () => {
    it("are exported as data at the root and in the traces, without touching any prototype", async () => {
        // JSON.parse creates own "__proto__" members; the loader keeps them as data (copyMembers)
        const text =
            '{"file_schema":"urn:ietf:params:qlog:file:contained","serialization_format":"application/qlog+json",' +
            '"__proto__":{"rootPolluted":"yes"},"traces":[{"vantage_point":{"type":"client"},' +
            '"__proto__":{"tracePolluted":"yes"},"events":[{"time":0,"name":"quic:packet_sent","data":{}}]}]}';
        const loaded = await loadQlogFile(text, "proto.qlog");
        const group = QlogLoader.fromJSON(loaded, { filename: "proto.qlog" })!;
        const out = groupToContainedQlog(group);
        const trace = (out.traces as Array<Record<string, unknown>>)[0];
        expect(Object.getPrototypeOf(out)).toBe(Object.prototype);
        expect(Object.getPrototypeOf(trace)).toBe(Object.prototype);
        expect(Object.prototype.hasOwnProperty.call(out, "__proto__")).toBe(true);
        expect(Object.prototype.hasOwnProperty.call(trace, "__proto__")).toBe(true);
        expect(out.rootPolluted).toBeUndefined();
        expect(trace.tracePolluted).toBeUndefined();
        const again = JSON.parse(serializeGroup(group)) as Record<string, unknown>;
        expect(Object.getOwnPropertyDescriptor(again, "__proto__")?.value).toEqual({ rootPolluted: "yes" });
        const againTrace = (again.traces as Array<Record<string, unknown>>)[0];
        expect(Object.getOwnPropertyDescriptor(againTrace, "__proto__")?.value).toEqual({ tracePolluted: "yes" });
        expect(({} as Record<string, unknown>).rootPolluted).toBeUndefined();
    });
});

