import { describe, expect, it } from "vitest";
import {
    combinedConnectionLabel,
    combinedHeaderLabel,
    connectionLabel,
    COMBINED_CONNECTION_PREFIX,
    groupOptionLabel,
} from "./connectionLabels";

// loader default for traces without vantage_point (parity/data-model.md §2.2)
const NO_VP = { name: "No VantagePoint set", type: "unknown", flow: "unknown" };

describe("connectionLabel (parity/app-shell.md §2.5.5 table)", () => {
    it.each([
        [
            { vantagePoint: { name: "aioquic client", type: "client" }, title: "Connection 1", description: "" },
            "aioquic client : client : Connection 1",
        ],
        [{ vantagePoint: { type: "server" }, title: "t", description: "d" }, "server : t : d"],
        [
            { vantagePoint: { type: "network", flow: "client" }, title: "", description: "" },
            "network (flow = client) : ",
        ],
        [{ vantagePoint: NO_VP, title: "x", description: "" }, "No VantagePoint set : unknown (flow = unknown) : x"],
        [{ vantagePoint: NO_VP, title: "", description: "" }, "No VantagePoint set : unknown (flow = unknown) : "],
        [
            {
                vantagePoint: { type: "unknown", flow: "unknown" },
                title: "ERROR",
                description: "/srv/a.qlog : File could not be found",
            },
            "unknown (flow = unknown) : ERROR : /srv/a.qlog : File could not be found",
        ],
        [{ vantagePoint: { type: "client" }, title: "Group abc : T", description: "" }, "client : Group abc : T"],
        [
            {
                vantagePoint: { name: "GENERATED", type: "server", flow: "unknown" },
                title: "Simulated, autogenerated trace : T",
                description: "Simulated, autogenerated trace : ",
            },
            "GENERATED : server (flow = unknown) : Simulated, autogenerated trace : T : Simulated, autogenerated trace : ",
        ],
    ])("%#: %j", (c, expected) => {
        expect(connectionLabel(c)).toBe(expected);
    });

    it("matches the getLongName() examples (parity/data-model.md §3.3.4)", () => {
        expect(connectionLabel({ vantagePoint: { type: "client" }, title: "conn", description: "" })).toBe(
            "client : conn",
        );
        expect(
            connectionLabel({ vantagePoint: { name: "aioquic client", type: "client" }, title: "", description: "d" }),
        ).toBe("aioquic client : client :  : d");
        expect(
            connectionLabel({ vantagePoint: { type: "network", flow: "client" }, title: "t", description: "" }),
        ).toBe("network (flow = client) : t");
    });

    it("prints UNKNOWN for a missing type and nothing for a missing vantage point", () => {
        expect(connectionLabel({ vantagePoint: {}, title: "t", description: "" })).toBe("UNKNOWN : t");
        expect(connectionLabel({ title: "t", description: "d" })).toBe("t : d");
    });
});

describe("other labels", () => {
    it("combined connection rows start with U+21B3 and a space", () => {
        expect(COMBINED_CONNECTION_PREFIX).toBe("↳ ");
        expect(combinedConnectionLabel({ vantagePoint: { type: "client" }, title: "c", description: "" })).toBe(
            "↳ client : c",
        );
    });

    it("group option: filename (title : description)", () => {
        expect(groupOptionLabel({ filename: "foo.qlog", title: "My title", description: "My description" })).toBe(
            "foo.qlog (My title : My description)",
        );
        expect(groupOptionLabel({ filename: "foo.qlog", title: "", description: "" })).toBe("foo.qlog ()");
        expect(groupOptionLabel({ filename: "foo.qlog", title: "", description: "d" })).toBe("foo.qlog (d)");
        expect(groupOptionLabel({ filename: "DEMO_new_cid.qlog (<1MB)", title: "", description: "" })).toBe(
            "DEMO_new_cid.qlog (<1MB) ()",
        );
    });

    it("combined header: filename (description), even when empty", () => {
        expect(combinedHeaderLabel({ parent: { filename: "f.qlog", description: "" } })).toBe("f.qlog ()");
        expect(combinedHeaderLabel({ parent: { filename: "f.qlog", description: "x" } })).toBe("f.qlog (x)");
    });
});
