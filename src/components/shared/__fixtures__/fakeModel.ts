// Minimal stand-ins for QlogConnectionGroup / QlogConnection (parity/data-model.md §3.16.12) for shell unit tests.
// Only the members the shell reads are implemented; instances are cast to the real model types.

import type { QlogConnection } from "@/model/QlogConnection";
import type { QlogConnectionGroup } from "@/model/QlogConnectionGroup";

export interface FakeVantagePoint {
    name?: string;
    type?: string;
    flow?: string;
}

export interface FakeTrace {
    title?: string;
    description?: string;
    vantagePoint?: FakeVantagePoint;
}

export class FakeGroup {
    filename: string;
    title = "";
    description = "";
    URL = "";
    URLshort = "";
    private readonly connections: FakeConnection[] = [];

    constructor(filename: string, title = "", description = "") {
        this.filename = filename;
        this.title = title;
        this.description = description;
    }

    addConnection(c: FakeConnection): void {
        this.connections.push(c);
    }

    getConnections(): readonly FakeConnection[] {
        return this.connections;
    }
}

export class FakeConnection {
    readonly parent: FakeGroup;
    title: string;
    description: string;
    vantagePoint: FakeVantagePoint;
    wasAutoGenerated = false;
    readonly timing = { timeOffset: 0 };

    constructor(parent: FakeGroup, trace: FakeTrace = {}) {
        this.parent = parent;
        this.title = trace.title ?? "";
        this.description = trace.description ?? "";
        this.vantagePoint = trace.vantagePoint ?? { name: "No VantagePoint set", type: "unknown", flow: "unknown" };
        parent.addConnection(this);
    }
}

/** Builds a group with one connection per trace and returns it typed as the real model class. */
export function makeGroup(
    filename: string,
    traces: FakeTrace[],
    opts: { title?: string; description?: string } = {},
): QlogConnectionGroup {
    const g = new FakeGroup(filename, opts.title ?? "", opts.description ?? "");
    for (const t of traces) {
        new FakeConnection(g, t);
    }
    return g as unknown as QlogConnectionGroup;
}

/** Adds one more connection to an existing (fake) group, like the sequence diagram's generated sibling. */
export function addConnection(group: QlogConnectionGroup, trace: FakeTrace): QlogConnection {
    return new FakeConnection(group as unknown as FakeGroup, trace) as unknown as QlogConnection;
}

export function conn(group: QlogConnectionGroup, index: number): QlogConnection {
    return group.getConnections()[index];
}
