import { modelEvents } from "@/model/modelEvents";
import type { QlogConnection } from "@/model/QlogConnection";
import { evt, loadGroup, pkt, seqTrace, type Json } from "./__fixtures__/seq";
import { ensureMoreThanOneTrace, guessPerspective, IGNORE_EVENT_TYPE } from "./mirror";
import { getGeneratedSibling } from "./timeModel";

beforeEach(() => {
    vi.spyOn(console, "warn").mockImplementation(() => {});
    vi.spyOn(console, "info").mockImplementation(() => {});
});
afterEach(() => vi.restoreAllMocks());

const EVENTS = [
    evt(0, "quic:connection_started", {}),
    pkt(1, "sent", "initial", 0),
    pkt(5, "received", "initial", 0),
    evt(6, "quic:recovery_metrics_updated", { latest_rtt: 4 }),
];

function conn(vp: Json | undefined, events: Json[] = EVENTS): QlogConnection {
    return loadGroup([seqTrace(events, vp, { title: "T", description: "D" })]).getConnections()[0];
}

const wrap = (connection: QlogConnection) => ({ connection, timeOffset: 0 });

describe("ensureMoreThanOneTrace (§3.4)", () => {
    it("client: generates a server mirror on the right, registered in the group", () => {
        const c = conn({ type: "client", name: "quic-go" });
        const changes: string[] = [];
        const off = modelEvents.on((ch) => changes.push(ch.kind));
        const traces = ensureMoreThanOneTrace([wrap(c)]);
        off();
        expect(traces).toHaveLength(2);
        const mirror = traces[1].connection;
        expect(traces[0].connection).toBe(c);
        expect(traces[1].timeOffset).toBe(0);
        expect(mirror.wasAutoGenerated).toBe(true);
        expect(mirror.title).toBe("Simulated, autogenerated trace : T");
        expect(mirror.description).toBe("Simulated, autogenerated trace : D");
        expect(mirror.vantagePoint).toEqual({ type: "server", flow: "unknown", name: "GENERATED" });
        expect(c.parent.getConnections()).toEqual([c, mirror]);
        expect(changes).toContain("connection-added");
        expect(getGeneratedSibling(c)).toBe(mirror);
        expect(getGeneratedSibling(mirror)).toBe(c);
        // events: packet names swapped, others ignored; raw objects shared and untouched
        expect(mirror.getEvents().map((e) => e.fullName)).toEqual([
            "quic:" + IGNORE_EVENT_TYPE,
            "quic:packet_received",
            "quic:packet_sent",
            "quic:" + IGNORE_EVENT_TYPE,
        ]);
        expect(mirror.getEvents()[1].raw).toBe(c.getEvents()[1].raw);
        expect(mirror.getEvents()[1].raw.name).toBe("quic:packet_sent");
        expect(mirror.lookup("quic", "packet_received")).toHaveLength(1);
        expect(c.getEvents()[1].fullName).toBe("quic:packet_sent");
    });

    it("server (or network flow server): client mirror on the left", () => {
        for (const vp of [{ type: "server" }, { type: "network", flow: "server" }]) {
            const s = conn(vp);
            const traces = ensureMoreThanOneTrace([wrap(s)]);
            expect(traces[1].connection).toBe(s);
            expect(traces[0].connection.vantagePoint).toMatchObject({
                type: "client",
                flow: "unknown",
                name: "GENERATED",
            });
        }
    });

    it("unknown vantage point: guess from the Initials and rename both", () => {
        const u = conn(undefined);
        expect(guessPerspective(u)).toBe("client"); // Initial 0 sent (1) before received (5)
        const traces = ensureMoreThanOneTrace([wrap(u)]);
        expect(traces[0].connection).toBe(u);
        expect(u.vantagePoint.type).toBe("unknown");
        expect(u.vantagePoint.name).toBe("vantage point type was unknown, pretending it's client");
        expect(traces[1].connection.vantagePoint).toEqual({
            type: "server",
            flow: "unknown",
            name: "vantage point type was unknown, pretending it's server",
        });

        const u2 = conn({ type: "transport" }, [pkt(0, "received", "initial", 0), pkt(1, "sent", "initial", 0)]);
        expect(guessPerspective(u2)).toBe("server");
        const traces2 = ensureMoreThanOneTrace([wrap(u2)]);
        expect(traces2[1].connection).toBe(u2);
        expect(traces2[0].connection.vantagePoint.type).toBe("client");

        // no Initials at all: default server
        expect(guessPerspective(conn(undefined, [evt(0, "http3:frame_created", {})]))).toBe("server");
    });

    it("reuses the generated sibling and places it by perspective (SQ7 FIX)", () => {
        const s = conn({ type: "server" });
        const first = ensureMoreThanOneTrace([wrap(s)]);
        const mirror = first[0].connection;
        const again = ensureMoreThanOneTrace([wrap(s)]);
        expect(again.map((t) => t.connection)).toEqual([mirror, s]); // qvis appended the client on the right
        expect(s.parent.getConnections()).toHaveLength(2); // not generated twice
        // only the mirror selected: its original goes to the other side
        expect(ensureMoreThanOneTrace([wrap(mirror)]).map((t) => t.connection)).toEqual([mirror, s]);
        const c = conn({ type: "client" });
        const cm = ensureMoreThanOneTrace([wrap(c)])[1].connection;
        expect(ensureMoreThanOneTrace([wrap(cm)]).map((t) => t.connection)).toEqual([c, cm]);
    });

    it("dedupes by connection (SQ6 FIX), then mirrors a single remaining trace", () => {
        const c = conn({ type: "client" });
        const w1 = wrap(c);
        const traces = ensureMoreThanOneTrace([w1, wrap(c)]);
        expect(traces).toHaveLength(2);
        expect(traces[0]).toBe(w1);
        expect(traces[1].connection.wasAutoGenerated).toBe(true);
        const s = conn({ type: "server" });
        const pair = [wrap(c), wrap(s)];
        expect(ensureMoreThanOneTrace(pair)).toEqual(pair);
    });
});
