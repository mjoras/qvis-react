const DIR = join(__dirname, "../../../tests/fixtures/latest");

function load(name: string, URL?: string): QlogConnectionGroup {
    const g = QlogLoader.fromJSON(parseQlogText(readFileSync(join(DIR, name), "utf8")), { filename: name, URL });
    if (!g) throw new Error("could not load " + name);
    g.filename = name;
    g.URL = URL ?? "";
    g.URLshort = URL ?? "";
    return g;
}

beforeEach(() => {
    vi.spyOn(console, "warn").mockImplementation(() => {});
    vi.spyOn(console, "info").mockImplementation(() => {});
    vi.spyOn(console, "log").mockImplementation(() => {});
});
afterEach(() => vi.restoreAllMocks());

const count = (arrs: Int32Array[]) => arrs.reduce((n, a) => n + a.filter((x) => x >= 0).length, 0);
const lostCount = (arrs: Uint8Array[], bit: number) => arrs.reduce((n, a) => n + a.filter((x) => x & bit).length, 0);

function packetCount(layout: SeqLayout, t: number, type: string): number {
    return layout.traces[t].connection.lookup("quic", type).length;
}

describe("prepareDiagram on real quic-go latest-draft traces", () => {
    it("client + server in one file: the pair, an automatic offset, every arrow matched", () => {
        const g = load("sequence-newcid-both.qlog");
        const sel = selectConnection([], 0, g.getConnections()[0]);
        expect(sel.map((s) => s.connection.vantagePoint.type)).toEqual(["client", "server"]);
        const r = prepareDiagram(sel, 1)!;
        const L = r.layout;
        expect(r.tracesChanged).toBe(true); // the offset was written into a new wrapper
        expect(L.traces[0]).toBe(sel[0]);
        // client Initial at relative 1.303 ms, seeded -5 ms; RTT/2 = 17.88; server got it at relative 0.144 ms
        expect(L.traces[1].timeOffset).toBeCloseTo(14.0419, 3);
        // every client packet arrives (right), every server packet arrives (left): no loss on this run
        expect(count(L.right)).toBe(packetCount(L, 0, "packet_sent"));
        expect(count(L.left)).toBe(packetCount(L, 1, "packet_sent"));
        expect(lostCount(L.lost, LOST_RIGHT | LOST_LEFT)).toBe(0);
        // arrows point down: received after sent once aligned
        L.right[0].forEach((t, i) => {
            if (t >= 0) expect(L.y[1][t]).toBeGreaterThanOrEqual(L.y[0][i]);
        });
        L.left[1].forEach((t, i) => {
            if (t >= 0) expect(L.y[0][t]).toBeGreaterThanOrEqual(L.y[1][i]);
        });
        expect(L.height).toBeGreaterThan(1000);
        expect(L.intervals.length).toBeGreaterThan(0);

        // second render of the written-back config: same result, nothing to write back
        const again = prepareDiagram(L.traces, 1)!;
        expect(again.tracesChanged).toBe(false);
        expect(Array.from(again.layout.y[1])).toEqual(Array.from(L.y[1]));

        // "Add trace" appends the first trace again: drawn once (SQ6), but the new selector stays in the config
        const added = [...L.traces, { connection: L.traces[0].connection, timeOffset: 0 }];
        const withDuplicate = prepareDiagram(added, 1)!;
        expect(withDuplicate.layout.traces).toEqual(L.traces);
        expect(withDuplicate.tracesChanged).toBe(false);
    });

    it("single trace: mirrored, every arrow horizontal, never lost", () => {
        const g = load("sequence-newcid-server.sqlog");
        const r = prepareDiagram(selectConnection([], 0, g.getConnections()[0]), 1)!;
        const L = r.layout;
        expect(L.traces.map((t) => t.connection.vantagePoint.type)).toEqual(["client", "server"]);
        expect(L.traces[0].connection.wasAutoGenerated).toBe(true);
        expect(g.getConnections()).toHaveLength(2);
        expect(lostCount(L.lost, LOST_RIGHT | LOST_LEFT)).toBe(0);
        expect(count(L.right) + count(L.left)).toBe(
            packetCount(L, 1, "packet_sent") + packetCount(L, 1, "packet_received"),
        );
        L.right[0].forEach((t, i) => {
            if (t >= 0) expect(L.y[1][t]).toBe(L.y[0][i]);
        });
        L.left[1].forEach((t, i) => {
            if (t >= 0) expect(L.y[0][t]).toBe(L.y[1][i]);
        });
        // generated events keep the original's y
        expect(Array.from(L.y[0])).toEqual(Array.from(L.y[1]));
    });

    it("lossy pair from two files: packets the peer never logged are presumed lost", () => {
        const client = load("sequence-lossy-client.sqlog").getConnections()[0];
        const server = load("sequence-lossy-server.sqlog").getConnections()[0];
        const r = prepareDiagram(
            [
                { connection: client, timeOffset: 0 },
                { connection: server, timeOffset: 0 },
            ],
            1,
        )!;
        const L = r.layout;
        const lostRight = lostCount(L.lost, LOST_RIGHT);
        const lostLeft = lostCount(L.lost, LOST_LEFT);
        expect(lostRight + lostLeft).toBeGreaterThan(0);
        expect(count(L.right) + lostRight).toBe(packetCount(L, 0, "packet_sent"));
        expect(count(L.left) + lostLeft).toBe(packetCount(L, 1, "packet_sent"));
        // every lost packet has a half-arrow target
        L.lost.forEach((lost, t) =>
            lost.forEach((bits, i) => {
                if (bits) expect(Number.isFinite(L.lostTargetY[t][i])).toBe(true);
            }),
        );
        // the server's own packet_lost events roughly agree with the presumed losses
        expect(server.lookup("quic", "packet_lost").length).toBeGreaterThan(0);
    });

    it("drops traces without events; none at all -> undefined", () => {
        const g = load("sequence-newcid-client.sqlog");
        const c = g.getConnections()[0];
        const error = vi.spyOn(console, "error").mockImplementation(() => {});
        const empty = { ...c, getEvents: () => [] } as unknown as typeof c;
        expect(prepareDiagram([{ connection: empty, timeOffset: 0 }], 1)).toBeUndefined();
        // addendum S6: a diagnostic, not an internal fault
        expect(console.warn).toHaveBeenCalledWith(
            "SequenceDiagramD3Renderer:setup : None of the selected traces have events in them, cannot render",
        );
        expect(error).not.toHaveBeenCalled();
        const r = prepareDiagram(
            [
                { connection: c, timeOffset: 0 },
                { connection: empty, timeOffset: 0 },
            ],
            1,
        )!;
        expect(r.tracesChanged).toBe(true);
        expect(r.layout.traces.map((t) => t.connection.wasAutoGenerated)).toEqual([false, true]);
    });
});

describe("event detail on real traces (§2.8, §3.14)", () => {
    const URL = "https://example.org/traces/sequence-newcid-both.qlog";
    const location = { origin: "https://qvis.example", pathname: "/app/" };

    it("raw JSON, event number, recovery metrics fold and the deep link", () => {
        const g = load("sequence-newcid-both.qlog", URL);
        const L = prepareDiagram(selectConnection([], 0, g.getConnections()[0]), 1)!.layout;
        const events = L.traces[0].connection.getEvents();
        const metricsIndex = events.findIndex((e, i) => i > 20 && e.fullName === "quic:recovery_metrics_updated");
        const d = buildEventDetail(L, 0, metricsIndex, location)!;
        expect(d.eventDetail).toBe(
            "Event nr: " + metricsIndex + "\n" + JSON.stringify(events[metricsIndex].raw, null, 2),
        );
        expect(d.eventDetail).not.toContain("timeText");
        const folded = JSON.parse(d.eventDetailExtra!);
        expect(folded).toMatchObject(events[metricsIndex].data);
        expect(Object.keys(folded)).toContain("congestion_window"); // carried forward from an earlier update
        expect(aggregateMetrics(events[metricsIndex])).toEqual(folded);
        expect(d.eventLink).toBe(
            "https://qvis.example/app/#/sequence?file=" +
                encodeURIComponent(URL) +
                "&focusOnConnection=0&focusOnEvent=" +
                metricsIndex,
        );
        // other events: no extra
        expect(buildEventDetail(L, 1, 0, location)!.eventDetailExtra).toBeNull();
    });

    it("no URL: no link; two URLs: file1/file2", () => {
        const c = load("sequence-lossy-client.sqlog").getConnections()[0];
        const s = load("sequence-lossy-server.sqlog").getConnections()[0];
        const L = prepareDiagram(
            [
                { connection: c, timeOffset: 0 },
                { connection: s, timeOffset: 0 },
            ],
            1,
        )!.layout;
        expect(buildEventDetail(L, 0, 3, location)!.eventLink).toBeNull();
        c.parent.URL = "https://a.org/c.sqlog";
        s.parent.URL = "https://a.org/s.sqlog";
        expect(buildEventDetail(L, 1, 3, location)!.eventLink).toBe(
            "https://qvis.example/app/#/sequence?file1=" +
                encodeURIComponent("https://a.org/c.sqlog") +
                "&file2=" +
                encodeURIComponent("https://a.org/s.sqlog") +
                "&focusOnConnection=1&focusOnEvent=3",
        );
    });

    it("SQ3 FIX: a click on the generated trace shows the original event; Event nr stays the clicked one", () => {
        const g = load("sequence-newcid-server.sqlog");
        const L = prepareDiagram(selectConnection([], 0, g.getConnections()[0]), 1)!.layout;
        const generated = L.traces[0].connection;
        const original = L.traces[1].connection;
        expect(generated.wasAutoGenerated).toBe(true);
        // a generated packet_sent (= the server's packet_received) and a generated packet_received
        const sentIdx = generated.getEvents().findIndex((e) => e.type === "packet_sent");
        const recvIdx = generated.getEvents().findIndex((e) => e.type === "packet_received");
        for (const idx of [sentIdx, recvIdx]) {
            const shown = resolveShownEvent(L, 0, idx)!;
            expect(shown.conn).toBe(original);
            expect(shown).toBe(original.getEvents()[idx]);
            expect(buildEventDetail(L, 0, idx, location)!.eventDetail.startsWith("Event nr: " + idx + "\n")).toBe(true);
        }
        // the original trace shows its own events
        expect(resolveShownEvent(L, 1, sentIdx)).toBe(eventAt(L, 1, sentIdx));
    });
});

describe("strict latest drafts (addendum S2: non-conforming events are drawn as generic chips)", () => {
    it("events with pre-final names are laid out like any unknown event, but never matched", async () => {
        const { evt, loadGroup, pkt, seqTrace } = await import("./__fixtures__/seq");
        const c = loadGroup([
            seqTrace(
                [
                    pkt(0, "sent", "initial", 0),
                    evt(1, "transport:packet_sent", { header: { packet_type: "initial", packet_number: 1 } }),
                    evt(2, "recovery:metrics_updated", { latest_rtt: 3 }),
                    evt(3, "quic:metrics_updated", {}),
                    evt(4, "http:frame_created", { stream_id: 0 }),
                ],
                { type: "client" },
            ),
        ]).getConnections()[0];
        const L = prepareDiagram([{ connection: c, timeOffset: 0 }], 1)!.layout;
        expect(Array.from(L.y[0]).every((y) => Number.isFinite(y))).toBe(true);
        expect(Array.from(L.y[1])).toEqual(Array.from(L.y[0]));
        // only quic:packet_sent gets an arrow (to the mirror); transport:packet_sent is a generic event
        expect(Array.from(L.right[0]).map((t) => t >= 0)).toEqual([true, false, false, false, false]);
        expect(L.lost[0].every((b) => b === 0)).toBe(true);

        // a trace with only pre-final events is still rendered (mirrored, no arrows, no console.error)
        const error = vi.spyOn(console, "error").mockImplementation(() => {});
        const legacy = loadGroup([
            seqTrace([evt(0, "transport:packet_sent", { header: { packet_type: "initial", packet_number: 0 } })], {
                type: "client",
            }),
        ]).getConnections()[0];
        const r = prepareDiagram([{ connection: legacy, timeOffset: 0 }], 1)!;
        expect(r.layout.traces).toHaveLength(2);
        expect(r.layout.y[0][0]).toBe(80);
        expect(count(r.layout.right) + count(r.layout.left)).toBe(0);
        expect(error).not.toHaveBeenCalled();
    });

    it("the real non-conforming quic-go output: every event laid out, no arrows (S2 reference input)", () => {
        const path = join(__dirname, "../../../tests/fixtures/nonconforming/h3-1x1M-noloss-client.sqlog");
        let text: string;
        try {
            text = readFileSync(path, "utf8");
        } catch {
            return; // fixture moved
        }
        const error = vi.spyOn(console, "error").mockImplementation(() => {});
        const g = QlogLoader.fromJSON(parseQlogText(text), { filename: "nc.sqlog" })!;
        const c = g.getConnections()[0];
        expect(c.getEvents().filter((e) => e.namespace === "transport").length).toBeGreaterThan(100);
        const L = prepareDiagram(selectConnection([], 0, c), 1)!.layout;
        expect(L.traces).toHaveLength(2);
        const t = L.traces.findIndex((tr) => tr.connection === c);
        expect(Array.from(L.y[t]).every((y) => Number.isFinite(y))).toBe(true);
        expect(count(L.right) + count(L.left)).toBe(0);
        expect(lostCount(L.lost, LOST_RIGHT | LOST_LEFT)).toBe(0);
        expect(error).not.toHaveBeenCalled();
    });
});

describe("converter TCP traces (addendum S3)", () => {
    it("tshark wikipedia_Playstation: tcp:packet_* arrows to the mirror, blue HTTP/2 frame chips", () => {
        let text: string;
        try {
            text = gunzipSync(
                readFileSync(join(__dirname, "../../../tests/fixtures/tshark/wikipedia_Playstation.json.gz")),
            ).toString("utf8");
        } catch {
            return; // fixture moved
        }
        const qlog = convertTshark(text, { filename: "wiki.json" }).qlog;
        const g = QlogLoader.fromJSON(
            { root: qlog as unknown as Record<string, unknown>, serialization: "json", diagnostics: [] },
            { filename: "wiki.json" },
        )!;
        const c = g.getConnections().find((conn) => conn.lookup("http2", "frame_created").length > 0)!;
        expect(c.transportNamespace).toBe("tcp");
        const L = prepareDiagram(selectConnection([], 0, c), 1)!.layout;
        expect(L.traces).toHaveLength(2);
        const sent = c.lookup("tcp", "packet_sent").length + c.lookup("tcp", "packet_received").length;
        expect(sent).toBeGreaterThan(0);
        expect(count(L.right) + count(L.left)).toBe(sent);
        expect(lostCount(L.lost, LOST_RIGHT | LOST_LEFT)).toBe(0);
        const h2 = c.lookup("http2", "frame_created")[0];
        expect(eventTypeToColor(h2)).toEqual(["#0468cc", "#FFFFFF"]);
        expect(eventToShortString(h2)).toMatch(/created|\(stream \d+\)/);
    });
});
