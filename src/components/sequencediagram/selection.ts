// Trace selection heuristics of the configurator (qvis SequenceDiagramConfigurator.vue:94-260;
// parity/sequence-diagram.md §3.15, SQ1, SQ8). Pure: every function returns a NEW connections array.

import type { QlogConnection } from "@/model/QlogConnection";
import type { QlogConnectionGroup } from "@/model/QlogConnectionGroup";
import SequenceDiagramConfig, { type SequenceDiagramConnection } from "./data/SequenceDiagramConfig";

const wrap = (c: QlogConnection): SequenceDiagramConnection => SequenceDiagramConfig.createConnectionWithTimeoffset(c);

function setAt(
    current: readonly SequenceDiagramConnection[],
    index: number,
    conn: QlogConnection,
): SequenceDiagramConnection[] {
    const next = current.slice();
    next[index] = wrap(conn);
    // Vue.set beyond the end behaves like push; never leave holes
    return next.filter((c) => c !== undefined);
}

/** `onConnectionSelected(index, conn)`: the first matching case (A-E) wins. */
export function selectConnection(
    current: readonly SequenceDiagramConnection[],
    index: number,
    conn: QlogConnection,
): SequenceDiagramConnection[] {
    const all = conn.parent.getConnections();
    const nonGenerated = all.filter((c) => !c.wasAutoGenerated);

    // A. a file with a single trace in the leftmost selector: show it (its counterpart is auto-generated)
    if (index === 0 && nonGenerated.length === 1) {
        return [wrap(all[0])];
    }

    // B. two traces: we expect 1 client and 1 server perspective
    if (nonGenerated.length === 2) {
        const firstConnection = all[0];
        const secondConnection = all[1];
        const firstPerspective = firstConnection.getVantagePointPerspective();
        const secondPerspective = secondConnection.getVantagePointPerspective();

        if (firstPerspective === secondPerspective) {
            // no client + server (typically a file that uses group_id): take the one that was selected
            return [wrap(conn)];
        }
        if (firstPerspective === "client") return [wrap(firstConnection), wrap(secondConnection)];
        if (secondPerspective === "client") return [wrap(secondConnection), wrap(firstConnection)];
        // SQ8 FIX: neither is a client (e.g. server + unknown): plain replacement (case E)
        return setAt(current, index, conn);
    }

    // C. more traces: take the selected one and the following ones with a different perspective
    // (e.g. client, network, network, server), but not a run of traces with the same vantage point
    if (all.length > 2) {
        const renderables = [wrap(conn)];
        const connectionIndexInParent = all.indexOf(conn);
        const firstPerspective = conn.getVantagePointPerspective();
        for (let i = connectionIndexInParent + 1; i < all.length; ++i) {
            // we skip autogenerated traces: they are selected by the renderer if needed
            if (all[i].getVantagePointPerspective() !== firstPerspective && !all[i].wasAutoGenerated) {
                renderables.push(wrap(all[i]));
            } else {
                break;
            }
        }
        return renderables;
    }

    // D. the user changed a right-hand selector: if all selected traces now have the same vantage point, prefer the
    // first non-autogenerated one
    if (index > 0) {
        let previousVantagePoint: string = "unknown";
        let firstNonAutogenerated: QlogConnection | undefined; // NB: ends up holding the LAST one (qvis)
        for (let i = 0; i < current.length; ++i) {
            const c = i === index ? conn : current[i].connection;
            const vantagePoint = c.vantagePoint.type;
            if (!c.wasAutoGenerated) firstNonAutogenerated = c;

            if (i !== 0 && vantagePoint !== previousVantagePoint) {
                // not all of the same type, user can solve the situation themself
                return setAt(current, index, conn);
            }
            previousVantagePoint = vantagePoint;
        }

        // all the same from here on
        if (previousVantagePoint === "network") {
            // special allowance for network traces (pcap2qlog: every trace is network with flow client)
            return setAt(current, index, conn);
        }

        if (firstNonAutogenerated !== undefined) {
            console.warn(
                "SequenceDiagramConfigurator: all selected traces had the same vantagePoint, auto-selecting the first non-autogenerated trace",
            );
            return [wrap(firstNonAutogenerated)];
        }
        console.warn(
            "SequenceDiagramConfigurator: all selected traces had the same vantagePoint and were also auto-generated. Trying to find a proper trace.",
        );
        for (const c of conn.parent.getConnections()) {
            if (!c.wasAutoGenerated) return [wrap(c)];
        }
        console.warn(
            "SequenceDiagramConfigurator: Proper trace not found, keeping last selected connection. THIS SHOULD NOT HAPPEN!",
        );
        return [wrap(conn)];
    }

    // E.
    return setAt(current, index, conn);
}

/** First connection of the first group that has one (app-shell Q12 FIX), or undefined. */
export function firstAvailableConnection(groups: readonly QlogConnectionGroup[]): QlogConnection | undefined {
    for (const g of groups) {
        const c = g.getConnections()[0];
        if (c !== undefined) return c;
    }
    return undefined;
}

/**
 * Default selection (mount, updated, URL load). SQ1 FIX: the same heuristic as a user pick in selector 0, so a file
 * with a client and a server trace opens as the pair.
 */
export function defaultSelection(groups: readonly QlogConnectionGroup[]): SequenceDiagramConnection[] | undefined {
    const first = firstAvailableConnection(groups);
    return first === undefined ? undefined : selectConnection([], 0, first);
}

/** "Add trace" (qvis `selectDefault`): appends the first trace of the first file, even when it is already shown. */
export function addDefaultTrace(
    current: readonly SequenceDiagramConnection[],
    groups: readonly QlogConnectionGroup[],
): SequenceDiagramConnection[] {
    const first = firstAvailableConnection(groups);
    return first === undefined ? current.slice() : [...current, wrap(first)];
}

/** `allowCustomTimeOffset`: only for index > 0 and when no selected trace is auto-generated. */
export function allowCustomTimeOffset(connections: readonly SequenceDiagramConnection[], index: number): boolean {
    return index > 0 && connections.find((c) => c.connection.wasAutoGenerated) === undefined;
}

const KNOWN_VANTAGE_POINT_TYPES = new Set(["client", "server", "network"]);

/**
 * `connectionIsUnknownPerspective` (alert C8): the first trace, or the second one when the first is auto-generated.
 * LD6: any type other than client / server / network counts as unknown (qvis: `=== "unknown"`).
 */
export function connectionIsUnknownPerspective(connections: readonly SequenceDiagramConnection[]): boolean {
    if (connections.length === 0) return false;
    let connection = connections[0].connection;
    if (connection.wasAutoGenerated && connections.length > 1) connection = connections[1].connection;
    return (
        connection.getEvents().length > 0 &&
        !!connection.vantagePoint &&
        !KNOWN_VANTAGE_POINT_TYPES.has(connection.vantagePoint.type)
    );
}
