// Automatic latency offset between a client and a server trace (qvis `calculateTimeOffsets`,
// SequenceDiagramD3Renderer.ts:581-784; parity/sequence-diagram.md §3.5.2, §9.5, SQ4, SQ5, SQ19).
//
// Both traces run on unsynchronized clocks. The offset of traces[1] ("server") is estimated so that the server
// receives the client's first Initial one one-way latency after the client sent it. The one-way latency comes from
// quic:recovery_metrics_updated (latest_rtt, else smoothed_rtt) or, failing that, from the client's Initial RTT.

import { NS, QUIC } from "@/model/names";
import type { QlogConnection } from "@/model/QlogConnection";
import type { QlogEvent } from "@/model/QlogEvent";
import type { SequenceDiagramConnection } from "./data/SequenceDiagramConfig";
import { toNum } from "./labels";
import { isPacketReceived, isPacketSent } from "./mirror";
import {
    absoluteStartTime,
    absoluteTime,
    getRememberedOffset,
    isRelativeWithoutReference,
    rememberOffset,
    setRefTimeOverride,
} from "./timeModel";

const NOT_FOUND = Number.MIN_SAFE_INTEGER;

/** One-way latency (RTT / 2, ms) from the trace's quic:recovery_metrics_updated events, or NOT_FOUND. */
function oneWayFromMetrics(conn: QlogConnection): number {
    let latencyOneWay = NOT_FOUND;
    let smoothedBackup = 0; // only used if there are no latest_rtt's (smoothed isn't always correct initially)
    for (const ev of conn.lookup(NS.quic, QUIC.recovery_metrics_updated)) {
        const update = ev.data ?? {};
        const latest = toNum(update.latest_rtt);
        if (latest) {
            latencyOneWay = latest / 2;
        } else {
            const smoothed = toNum(update.smoothed_rtt);
            if (smoothed) smoothedBackup = smoothed / 2;
        }
        if (latencyOneWay !== NOT_FOUND) {
            latencyOneWay = ev.timeToMilliseconds(latencyOneWay); // always ms in the latest drafts
            break;
        }
    }
    if (latencyOneWay === NOT_FOUND && smoothedBackup !== 0) latencyOneWay = smoothedBackup;
    return latencyOneWay;
}

function initialHeader(ev: QlogEvent): Record<string, any> | undefined {
    const h = ev.data ? ev.data.header : undefined;
    return typeof h === "object" && h !== null && h.packet_type === "initial" ? h : undefined;
}

/**
 * Returns the new `timeOffset` for `traces[1]` (ms), or undefined to keep it. Remembers computed offsets per server
 * connection and may set a view-local reference-time override (the "HERE BE DRAGONS" repair). User-entered offsets
 * are remembered by the configurator (`rememberOffset(conn, v, true)`), so they win, including 0 (SQ5 FIX).
 */
export function calculateTimeOffsets(traces: readonly SequenceDiagramConnection[]): number | undefined {
    if (traces.length > 2) {
        console.warn(
            "SequenceDiagramD3Renderer:calculateTimeOffsets : no time offsets auto-calculated for more than 2 traces. Use the UI to assign them manually if needed.",
        );
        return undefined;
    }
    if (traces.length < 2) return undefined;

    const clientConnection = traces[0];
    const serverConnection = traces[1];
    const client = clientConnection.connection;
    const server = serverConnection.connection;

    if (server.wasAutoGenerated || client.wasAutoGenerated) return undefined;

    // was set in the qlog file (configuration.time_offset no longer exists: always 0)
    if (server.timing.timeOffset !== 0) return undefined;

    const remembered = getRememberedOffset(server);

    // was manually overridden (or computed before) while viewing this file: make sure it is persisted
    if (serverConnection.timeOffset) {
        if (!remembered || remembered.value !== serverConnection.timeOffset) {
            rememberOffset(server, serverConnection.timeOffset, false);
        }
        return undefined;
    }

    // was already calculated or manually overridden (including a user-entered 0) in a previous viewing of this file
    if (remembered !== undefined) {
        return remembered.value !== serverConnection.timeOffset ? remembered.value : undefined;
    }

    // A trace without reference time (epoch "unknown") starts at 0; align it to the other one (view-local, SQ19).
    if (isRelativeWithoutReference(client)) {
        console.warn(
            "SequenceDiagramD3Renderer:calculateTimeOffsets : Client had no reference_time set, trying to fix by using the server-side reftime. HERE BE DRAGONS!",
        );
        // -5 because the client should start earlier because it sends the initial
        setRefTimeOverride(client, absoluteStartTime(server) - 5);
    } else if (isRelativeWithoutReference(server)) {
        console.warn(
            "SequenceDiagramD3Renderer:calculateTimeOffsets : Server had no reference_time set, trying to fix by using the client-side reftime. HERE BE DRAGONS!",
        );
        // +5 because the server should start later because it receives the client's initial
        setRefTimeOverride(server, absoluteStartTime(client) + 5);
    }

    let latencyOneWay = oneWayFromMetrics(client);
    if (latencyOneWay === NOT_FOUND) latencyOneWay = oneWayFromMetrics(server);

    // the metrics-based approach can be flaky if there was loss, so we also correlate the actual Initials:
    // start with the first Initial the server got and work backwards from there
    let initialSent: QlogEvent | undefined;
    let initialReceived: QlogEvent | undefined;
    let serverInitialReceived: QlogEvent | undefined;
    let firstInitialReceivedPN = "0";

    for (const ev of server.getEvents()) {
        if (isPacketReceived(ev, server)) {
            const h = initialHeader(ev);
            if (h && h.packet_number !== undefined) {
                serverInitialReceived = ev;
                firstInitialReceivedPN = "" + h.packet_number; // e.g., if client Initials 0 and 1 were lost, this is 2
                break;
            }
        }
    }

    for (const ev of client.getEvents()) {
        if (isPacketSent(ev, client)) {
            const h = initialHeader(ev);
            if (h && "" + h.packet_number === firstInitialReceivedPN) initialSent = ev;
        }
        // the server's Initial could also be lost: just use the first one we've received from the server
        if (isPacketReceived(ev, client) && initialHeader(ev)) initialReceived = ev;
        if (initialSent && initialReceived) break;
    }

    if (initialSent && initialReceived && serverInitialReceived) {
        if (latencyOneWay === NOT_FOUND) {
            // only if it wasn't derived from metrics updates, which we assume are always correct
            latencyOneWay = (absoluteTime(initialReceived) - absoluteTime(initialSent)) / 2;
            if (latencyOneWay <= 0) {
                console.warn(
                    "SequenceDiagramD3Renderer:calculateTimeOffset : initial received is earlier than sent! ",
                    latencyOneWay,
                );
                return undefined;
            }
        }

        // we know when we would like the serverInitialReceived to have happened (clientInitialSent + latencyOneWay)
        const serverReceiveTime = absoluteTime(serverInitialReceived);
        const expectedServerReceiveTime = absoluteTime(initialSent) + latencyOneWay;
        latencyOneWay = expectedServerReceiveTime - serverReceiveTime; // SQ4 FIX: signed (qvis took the absolute value)
    } else if (latencyOneWay !== NOT_FOUND) {
        console.log(
            "SequenceDiagramD3Renderer:calculateTimeOffset: calculating probable RTT from metrics_updated events because initials couldn't be properly correlated (was there loss?)",
            latencyOneWay,
        );
    }

    if (latencyOneWay === NOT_FOUND) return undefined;

    console.log("SequenceDiagramD3Renderer:calculateTimeOffset : offset determined at ", latencyOneWay);
    rememberOffset(server, latencyOneWay, false);
    return latencyOneWay;
}
