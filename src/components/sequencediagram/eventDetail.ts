// SequenceDiagramRenderer.vue:85-150; parity/sequence-diagram.md §2.8, §3.14, SQ3, SQ14, app-shell Q18).

import { hrefFor } from "@/app/router";
import { QUIC_EVENTS } from "@/model/names";
import type { QlogEvent } from "@/model/QlogEvent";
import type { SeqLayout } from "./prepare";

export interface EventDetail {
    /** "Event nr: N\n" + the raw event JSON */
    eventDetail: string;
    /** JSON of all recovery metrics up to and including the event (recovery_metrics_updated only), else null */
    eventDetailExtra: string | null;
    /** "Direct link to this event" href, or null when the trace was not loaded from a URL */
    eventLink: string | null;
}

/** The QlogEvent at (trace, event index) of a layout. */
export function eventAt(layout: SeqLayout, trace: number, index: number): QlogEvent | undefined {
    const t = layout.traces[trace];
    return t ? t.connection.getEvents()[index] : undefined;
}

/**
 * SQ3 FIX: a click on an auto-generated trace shows its original counterpart: the forward arrow target when present,
 * else the event whose arrow targets the clicked one, else the clicked event itself.
 */
export function resolveShownEvent(layout: SeqLayout, trace: number, index: number): QlogEvent | undefined {
    const clicked = eventAt(layout, trace, index);
    if (clicked === undefined) return undefined;
    if (!layout.traces[trace].connection.wasAutoGenerated) return clicked;

    let other: QlogEvent | undefined;
    const right = layout.right[trace][index];
    const left = layout.left[trace][index];
    if (right >= 0) other = eventAt(layout, trace + 1, right);
    else if (left >= 0) other = eventAt(layout, trace - 1, left);
    else {
        // reverse: an event on a neighbouring trace whose arrow ends here
        if (trace > 0) {
            const idx = layout.right[trace - 1].indexOf(index);
            if (idx >= 0) other = eventAt(layout, trace - 1, idx);
        }
        if (other === undefined && trace < layout.traces.length - 1) {
            const idx = layout.left[trace + 1].indexOf(index);
            if (idx >= 0) other = eventAt(layout, trace + 1, idx);
        }
    }
    if (other !== undefined) {
        console.log("SequenceDiagramD3Renderer:onEventClicked : switched event from auto-generated to original");
        return other;
    }
    return clicked;
}

/** The value of every recovery metric at `ev`: fold of all recovery_metrics_updated data up to and including it. */
export function aggregateMetrics(ev: QlogEvent): Record<string, unknown> {
    const metrics = new Map<string, unknown>();
    for (const candidate of ev.conn.getEvents()) {
        if (candidate.fullName === QUIC_EVENTS.recovery_metrics_updated) {
            const data = candidate.data ?? {};
            for (const metricName of Object.keys(data)) metrics.set(metricName, data[metricName]);
        }
        if (candidate === ev) break; // don't go further than the current metrics update
    }
    return Object.fromEntries(metrics);
}

/** Distinct `parent.URL`s of the rendered traces, in trace order. */
function traceURLs(layout: SeqLayout): string[] {
    const urls: string[] = [];
    for (const t of layout.traces) {
        const url = t.connection.parent.URL;
        if (url && urls.indexOf(url) < 0) urls.push(url);
    }
    return urls;
}

/**
 * Deep link to an event (Q18 FIX): this app's own location, encoded parameters:
 * `<origin><path>#/sequence?file=<URL>&focusOnConnection=<t>&focusOnEvent=<e>` (`file1..N` for several files).
 */
export function eventLinkFor(
    layout: SeqLayout,
    trace: number,
    index: number,
    location: { origin: string; pathname: string } = window.location,
): string | null {
    const urls = traceURLs(layout);
    const t = layout.traces[trace];
    if (!t || urls.length === 0) {
        // qvis logs this (console.error) for every click when no trace was loaded from a URL; a diagnostic that fires
        // on valid input is a warning here (parity addendum S6)
        console.warn(
            "SequenceDiagramRenderer:showEventModal : trying to focus on trace, but doesn't exist: ",
            { connectionIndex: trace, eventIndex: index },
            layout.traces,
        );
        return null;
    }
    if (!t.connection.parent.URL) return null;

    const query: Record<string, string> = {};
    if (urls.length === 1) query.file = urls[0];
    else urls.forEach((u, i) => (query["file" + (i + 1)] = u));
    query.focusOnConnection = "" + trace;
    query.focusOnEvent = "" + index;
    return location.origin + location.pathname + hrefFor("/sequence", query);
}

/** Everything the popup shows for a click on (trace, event index). */
export function buildEventDetail(
    layout: SeqLayout,
    trace: number,
    index: number,
    location?: { origin: string; pathname: string },
): EventDetail | undefined {
    const shown = resolveShownEvent(layout, trace, index);
    if (shown === undefined) return undefined;

    // the raw event as logged: no timeText or other annotations (SQ14)
    const json = JSON.stringify(shown.raw, null, 2);
    const extra =
        shown.fullName === QUIC_EVENTS.recovery_metrics_updated
            ? JSON.stringify(aggregateMetrics(shown), null, 2)
            : null;

    return {
        eventDetail: "Event nr: " + index + "\n" + json,
        eventDetailExtra: extra,
        eventLink: eventLinkFor(layout, trace, index, location),
    };
}
