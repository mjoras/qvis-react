import { act, render, screen } from "@testing-library/react";
import { syncFromLocation } from "@/app/router";
import { resetConnectionStoreForTests, useConnectionStore } from "@/store/connectionStore";
import { useConfigurationStore } from "@/store/configurationStore";
import { resetNotificationsForTests, subscribeNotifications, type NotificationItem } from "@/lib/notify";
import { evt, loadGroup, pkt, seqTrace } from "./__fixtures__/seq";
import SequenceDiagramContainer from "./SequenceDiagramContainer";

beforeEach(() => {
    vi.spyOn(console, "warn").mockImplementation(() => {});
    vi.spyOn(console, "info").mockImplementation(() => {});
    vi.spyOn(console, "log").mockImplementation(() => {});
    resetConnectionStoreForTests();
    useConfigurationStore.getState().reset();
    resetNotificationsForTests();
});
afterEach(() => vi.restoreAllMocks());

const clientFile = () =>
    loadGroup(
        [
            seqTrace(
                [
                    evt(0, "quic:connection_started", {}),
                    pkt(1, "sent", "initial", 0, [{ frame_type: "crypto" }]),
                    pkt(30, "received", "initial", 0, [{ frame_type: "ack", acked_ranges: [[0, 0]] }]),
                    evt(31, "quic:recovery_metrics_updated", { latest_rtt: 29, smoothed_rtt: 29 }),
                ],
                { type: "client" },
                { title: "client trace" },
            ),
        ],
        "client.qlog",
    );

describe("<SequenceDiagramContainer/>", () => {
    it("without files: intro text, controls and the no-file alert", () => {
        render(<SequenceDiagramContainer />);
        expect(
            screen.getByText(
                "Select one or more traces via the dropdown(s) below to visualize them in the sequence diagram",
            ),
        ).toBeInTheDocument();
        expect(screen.getByRole("button", { name: "Add trace" })).toHaveClass("btn", "btn-secondary");
        expect(screen.getByText("Time multiplier:")).toHaveClass("text-right");
        expect(screen.getByRole("spinbutton")).toHaveValue(1);
        expect(screen.getByRole("alert")).toHaveTextContent("Please load a trace file to visualize it");
        const box = document.getElementById("sequence-diagram")!;
        expect(box.style.border).toBe("5px solid rgb(204, 229, 255)");
        expect(box.style.minHeight).toBe("200px");
        expect(document.getElementById("sequence-diagram-svg")!.childNodes).toHaveLength(0);
    });

    it("selects the first trace when a file arrives, mirrors it and writes the mirror back (one layout)", () => {
        render(<SequenceDiagramContainer />);
        const g = clientFile();
        act(() => useConnectionStore.getState().addGroup(g));
        const config = useConfigurationStore.getState().sequenceConfig;
        expect(config.connections.map((c) => c.connection.vantagePoint.type)).toEqual(["client", "server"]);
        expect(config.connections[1].connection.wasAutoGenerated).toBe(true);
        expect(g.getConnections()).toHaveLength(2);
        // two selectors, no latency offset for generated traces, no alerts
        expect(document.querySelectorAll(".sequence-diagram-configurator select")).toHaveLength(2);
        expect(screen.queryByText("Latency offset :")).toBeNull();
        expect(screen.queryByRole("alert")).toBeNull();
        // drawn: two timelines and the header labels
        const svg = document.getElementById("sequence-diagram-svg")!;
        expect(svg.querySelectorAll(":scope > rect")).toHaveLength(2);
        expect(Array.from(svg.querySelectorAll(":scope > text:not(.timestamp)")).map((t) => t.textContent)).toEqual([
            "client.qlog",
            "client",
            "GENERATED: client.qlog",
            "server",
        ]);
        expect(svg.querySelectorAll("rect[data-event]").length).toBe(6); // 4 + the 2 mirrored packets
    });

    describe("deep link landing (addendum S8)", () => {
        let style: HTMLStyleElement;
        let scrollTo: ReturnType<typeof vi.spyOn>;
        beforeEach(() => {
            window.history.replaceState(null, "", "#/sequence?focusOnConnection=0&focusOnEvent=3");
            syncFromLocation();
            // jsdom has no layout: the alert is 50 px high with Bootstrap's 16 px bottom margin
            style = document.createElement("style");
            style.textContent = ".alert { margin-bottom: 16px; }";
            document.head.appendChild(style);
            vi.spyOn(HTMLElement.prototype, "getBoundingClientRect").mockImplementation(function (this: HTMLElement) {
                const height = this.classList.contains("alert") ? 50 : 0;
                return { x: 0, y: 0, top: 0, left: 0, right: 0, bottom: height, width: 0, height } as DOMRect;
            });
            scrollTo = vi.spyOn(window, "scrollTo").mockImplementation(() => {});
        });
        afterEach(() => {
            style.remove();
            window.history.replaceState(null, "", "#/");
            syncFromLocation();
        });
        const focusedY = (): number =>
            Number(document.querySelector('rect[data-trace="0"][data-event="3"]')!.getAttribute("y")) + 6;

        it("files arriving while the view is shown: lower by the 'Loading files...' alert, as in qvis", () => {
            act(() => useConnectionStore.getState().adjustOutstandingRequestCount(1));
            render(<SequenceDiagramContainer />);
            expect(screen.getByRole("alert")).toHaveTextContent("Loading files...");
            act(() => {
                useConnectionStore.getState().addGroup(clientFile());
                useConnectionStore.getState().adjustOutstandingRequestCount(-1);
            });
            expect(screen.queryByRole("alert")).toBeNull();
            expect(scrollTo).toHaveBeenCalledTimes(1);
            // jsdom: the diagram box starts at 0, so the target (>= 50) was below the alert in qvis
            expect(focusedY() - 50).toBeGreaterThanOrEqual(50);
            expect(scrollTo).toHaveBeenCalledWith(0, Math.max(0, focusedY() - 50 - 66));
            // only once: a later render (time multiplier) does not scroll
            act(() => useConfigurationStore.getState().update("sequenceConfig", { timeResolution: 2 }));
            expect(scrollTo).toHaveBeenCalledTimes(1);
        });

        it("files already loaded when the view opens: y - 50", () => {
            act(() => useConnectionStore.getState().addGroup(clientFile()));
            render(<SequenceDiagramContainer />);
            expect(scrollTo).toHaveBeenCalledWith(0, focusedY() - 50);
        });

        it("large trace (SN1 and its 200 ms wait): y - 50, the alert was already gone in qvis", async () => {
            const events = Array.from({ length: 10001 }, (_, i) => pkt(i * 0.01, "sent", "1RTT", i));
            const big = loadGroup([seqTrace(events, { type: "client" })], "big.qlog");
            act(() => useConnectionStore.getState().adjustOutstandingRequestCount(1));
            render(<SequenceDiagramContainer />);
            act(() => {
                useConnectionStore.getState().addGroup(big);
                useConnectionStore.getState().adjustOutstandingRequestCount(-1);
            });
            expect(scrollTo).not.toHaveBeenCalled();
            await act(async () => {
                await new Promise((r) => setTimeout(r, 300));
            });
            expect(scrollTo).toHaveBeenCalledWith(0, focusedY() - 50);
        });
    });

    it("unknown vantage point: the heuristics alert; an empty trace: SN2", () => {
        const items: NotificationItem[] = [];
        const off = subscribeNotifications((n) => items.push(n));
        render(<SequenceDiagramContainer />);
        const g = loadGroup([seqTrace([pkt(0, "received", "initial", 0)], undefined)], "u.qlog");
        act(() => useConnectionStore.getState().addGroup(g));
        expect(screen.getByRole("alert")).toHaveTextContent(
            "The selected trace has an unknown vantage point. We guessed it based on heuristics, but this could be wrong!",
        );

        const error = vi.spyOn(console, "error").mockImplementation(() => {});
        const empty = { ...g.getConnections()[0], getEvents: () => [] } as unknown as (typeof g.getConnections)[never];
        act(() =>
            useConfigurationStore.getState().update("sequenceConfig", {
                connections: [{ connection: empty as never, timeOffset: 0 }],
            }),
        );
        expect(items.map((n) => n.title)).toContain("Trace could not be rendered");
        expect(items.find((n) => n.title === "Trace could not be rendered")!.text).toBe(
            "This trace could not be rendered. There could be an error or a previous file was still rendering.<br/>See the JavaScript devtools for more information.",
        );
        // addendum S6: "None of the selected traces have events" is a diagnostic (console.warn), not an error
        expect(error).not.toHaveBeenCalled();
        expect(console.warn).toHaveBeenCalledWith(
            "SequenceDiagramD3Renderer:setup : None of the selected traces have events in them, cannot render",
        );
        off();
    });
});
